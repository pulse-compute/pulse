'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const f = require('./report-fixtures.cjs');
const { createReportViewModel } = require(path.join(f.reportRoot, 'viewer/model'));
module.exports = ({renderedTree}) => {
  const capsule = f.createCapsule(f.fixture(true));
  const before = JSON.stringify(capsule), model = createReportViewModel(capsule);
  assert.match(model.entryLabel(capsule.entries[0]), /shared · GET \/same/);
  assert.notEqual(model.entryLabel(capsule.entries[0]), model.entryLabel(capsule.entries[1]), 'reused handlers retain distinct entry labels');
  assert.equal(model.entryLabel(undefined), 'Unknown entry reference');
  const tree = renderedTree(capsule);
  Object.assign(tree.renderers.state, {selected:capsule.routes[0].id,drawerTab:'facts'});
  tree.renderers.renderDrawer();
  assert.ok(tree.nodes().some(n=>n.tag==='a'&&n.attrs.href==='#entries/0'&&n.attrs.title===capsule.entries[0].id));
  Object.assign(tree.renderers.state, {selectedEntry:capsule.entries[0].id});
  tree.renderers.renderEntries();
  const detail = tree.get('view-entries').textContent;
  for (const text of [capsule.entries[0].id,capsule.entries[0].canonicalId,'src/routes.ts:1:1','Own route registrations','Recorded composition references']) assert.ok(detail.includes(text));
  assert.ok(tree.nodes().some(n=>n.attrs.href==='#routes/0'));
  tree.get('entry-search').events.input({target:{value:'src/routes.ts:2'}});
  assert.ok(tree.get('entry-list').textContent.includes(model.entryLabel(capsule.entries[1])));
  assert.ok(!tree.get('entry-list').textContent.includes(model.entryLabel(capsule.entries[0])));
  tree.location.hash='#entries/1';tree.renderers.onHash();
  assert.equal(tree.renderers.state.selectedEntry,capsule.entries[1].id);
  assert.equal(tree.document.activeElement.id,'entry-title');
  assert.equal(tree.surfaces['.workspace'].inert,false);
  assert.equal(tree.get('route-drawer').hidden,true);
  assert.equal(tree.get('view-entries').hidden,false);
  tree.location.hash='#routes/0';tree.renderers.onHash();
  assert.equal(tree.renderers.state.selected,capsule.routes[0].id);
  assert.equal(tree.get('route-drawer').hidden,false);
  tree.location.hash='#entries/999999';tree.renderers.onHash();
  assert.equal(tree.get('entry-title'),undefined,'invalid deep link safely shows inventory');
  assert.equal(tree.surfaces['.workspace'].inert,false);
  assert.equal(JSON.stringify(capsule), before, 'view state never mutates the capsule');
  assert.deepEqual(JSON.parse(model.canonicalJson), capsule);

  // Projection-only adversarial identities exercise shared-prefix handling.
  const collision = structuredClone(capsule);
  collision.entries[0].id='entry:12345678a'+'0'.repeat(55);
  collision.entries[1].id='entry:12345678b'+'0'.repeat(55);
  collision.entries.forEach(e=>{e.name=null;e.source=null;e.kind='middleware';delete e.flow;});
  const cm=createReportViewModel(collision);
  assert.equal(cm.entryLabel(collision.entries[0]),'middleware · 12345678a');
  assert.equal(cm.entryLabel(collision.entries[1]),'middleware · 12345678b');
  const reversed=createReportViewModel({...collision,entries:[...collision.entries].reverse()});
  assert.equal(reversed.entryLabel(collision.entries[0]),cm.entryLabel(collision.entries[0]), 'short identities do not depend on list order');
  const historical=renderedTree(collision);
  Object.assign(historical.renderers.state,{selectedEntry:collision.entries[0].id});historical.renderers.renderEntries();
  assert.match(historical.get('view-entries').textContent,/SourceNot recorded/);
  assert.match(historical.get('view-entries').textContent,/Recorded nameNot recorded/);
  collision.entries[0].name='<img src=x onerror=alert(1)>';
  const hostile=renderedTree(collision);hostile.renderers.renderEntries();
  assert.ok(hostile.get('entry-list').textContent.includes(collision.entries[0].name));
  assert.ok(!hostile.nodes().some(n=>n.tag==='img'));
};
