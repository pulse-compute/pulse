function renderDiagnostic(code, raw) {
  const descriptor = describeDiagnostic(code);
  const remediation = descriptor.remediation.map((entry, index) => `${index + 1}. ${entry}`).join('\n');
  const http = raw.httpStatus === undefined ? `${descriptor.httpStatus} fallback when surfaced by the development server` : String(raw.httpStatus);
  return `<a id="${diagnosticAnchor(code)}"></a>
### ${inlineCode(code)} — ${descriptor.title}

${descriptor.summary}

- **Category:** ${inlineCode(descriptor.category)}
- **CLI exit class:** ${inlineCode(descriptor.exitCode)}
- **Development HTTP status:** ${inlineCode(http)}
- **Stability/scope:** ${inlineCode(descriptor.stability)} / ${inlineCode(descriptor.scope)}
- **Related reference:** ${CATEGORY_RELATED[descriptor.category] || CATEGORY_RELATED.internal}

**Remediation**

${remediation}`;
}

