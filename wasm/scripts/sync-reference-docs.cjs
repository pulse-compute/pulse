function renderOptions(options, command) {
  if (options.length === 0) return '_No command-specific options._';
  const rows = options.map((option) => `| ${inlineCode(optionDisplay(option, command))} | ${optionDescription(option, command)} |`);
  return `| Option | Behavior |\n|---|---|\n${rows.join('\n')}`;
}

function renderCliReference() {
  const globalIds = new Set(['help', 'json', 'dry-run']);
  const globals = OPTION_SPECS.filter((entry) => entry.visibility === 'public' && globalIds.has(entry.id));
  const commands = PUBLIC_COMMAND_ORDER.map((name) => {
    const command = COMMAND_SPECS[name];
    const signatures = command.usage.join('\n');
    const positionals = command.positionals.length
      ? `\n### Positionals\n\n${command.positionals.map((entry) => `- ${inlineCode(entry.name)} — ${entry.description}`).join('\n')}\n`
      : '';
    const options = publicOptionsForCommand(name).filter((entry) => !globalIds.has(entry.id));
    const examples = command.examples.length
      ? `\n### Examples\n\n\`\`\`bash\n${command.examples.join('\n')}\n\`\`\`\n`
      : '';
    const diagnostics = command.diagnostics.length
      ? `\n### Related diagnostics\n\n${command.diagnostics.map((code) => `- [${inlineCode(code)}](diagnostics.md#${diagnosticAnchor(code)}) — ${DIAGNOSTIC_CATALOG[code].summary}`).join('\n')}\n`
      : '';
    return `## ${inlineCode(`pulse ${name}`)}

${command.summary}

${command.usage.length > 1 ? 'Supported signatures' : 'Syntax'}:

\`\`\`text
${signatures}
\`\`\`
${positionals}
### Options

${renderOptions(options, name)}
${examples}
${diagnostics}

### Output

${command.outputs.map((entry) => `- ${entry}`).join('\n')}

### Side effects

${command.sideEffects.map((entry) => `- ${entry}`).join('\n')}

### Exit behavior

${command.exit}`;
  }).join('\n\n');

  return stable(`# CLI reference

${GENERATED_NOTICE}

The ${inlineCode('pulse')} CLI in ${inlineCode('@pulse-compute/cli@' + RELEASE_VERSION)} is the supported project workflow. One command specification generates this page, installed help, and the shipped Bash, Zsh, and Fish completion scripts, so a public command or option cannot drift between those surfaces.

## Meta invocations

${META_INVOCATIONS.map((entry) => `- ${inlineCode(entry.syntax)} — ${entry.description}`).join('\n')}

## Global options

${renderOptions(globals)}

## Shell completion

Completion output is generated from the same public command and option specification as help and this reference. Tooling can consume the generated [machine-readable command specification](./cli-spec.json).

${COMPLETION_SHELLS.map((shell) => `### ${inlineCode(shell)}

\`\`\`bash
${shell === 'bash' ? 'source <(pulse completion bash)' : shell === 'zsh' ? 'source <(pulse completion zsh)' : 'pulse completion fish | source'}
\`\`\`

The package also ships ${inlineCode(`completions/${completionFile(shell)}`)}.`).join('\n\n')}

${commands}

## Configuration discovery and command precedence

Project commands start discovery from their optional positional ${inlineCode('[directory]')} or the current directory, then search upward for the single configuration entrypoint:

\`\`\`text
${CONFIG_DISCOVERY.join('\n')}
\`\`\`

Profile selection follows ${inlineCode('--profile')}, ${inlineCode('PULSE_PROFILE')}, then ${inlineCode('pulse.defaultProfile')}. Command-line ${inlineCode('--out')}, ${inlineCode('--host')}, ${inlineCode('--port')}, and watch flags are invocation-local controls. Entry, provider, and target selection belong to ${inlineCode('.pulse/config.ts')}: ${inlineCode('pulse compile')} remains provider-neutral and ${inlineCode('pulse build')} realizes the selected provider. See [Project configuration](project-config.md).

## JSON and stream contracts

For completed commands, ${inlineCode('--json')} emits one JSON object followed by a newline. ${inlineCode('pulse dev --json')} is deliberately different: stdout is newline-delimited JSON, with one event object per line. Event names are ${inlineCode('compiled')}, ${inlineCode('ready')}, ${inlineCode('reloaded')}, ${inlineCode('request')}, ${inlineCode('compile-error')}, and ${inlineCode('request-error')}; consumers must not wait for one enclosing JSON document.

Raw configured secret values are not included in project JSON, diagnostics, or runtime error detail fields.

## Provider restrictions and build products

| Provider | inspect/build | test/dev | Build result |
|---|---:|---:|---|
| ${inlineCode('node')} | Yes | Yes | Portable Pulse Wasm plus the configured Node-native realization and ${inlineCode('pulse-build.json')}. |
| ${inlineCode('fastly')} | Yes | Yes, through local conformance | Portable Pulse Wasm plus generated AssemblyScript and compact direct-host-ABI ${inlineCode('bin/main.wasm')}. |
| ${inlineCode('none')} | Compile only | No | ${inlineCode('pulse compile')} emits portable Pulse Wasm; ${inlineCode('pulse build')} rejects the missing deployment provider. |

Build output is cleaned by default. ${inlineCode('--no-clean')} preserves the directory, but output safety still rejects absolute, parent-traversal, and symbolic-link traversal outside the project root.

## Exit classes

| Exit | Meaning |
|---:|---|
| ${inlineCode('0')} | Command completed successfully. |
| ${inlineCode('1')} | Completed audit/test failure where documented, or an unexpected uncatalogued internal failure. |
| ${inlineCode('2')} | Usage, project configuration, provider selection, or output-safety error. |
| ${inlineCode('3')} | Canonical/schema/package-lowering/provider-binding failure. |
| ${inlineCode('4')} | Request, test, runtime, fetch, or continuation failure. |
| ${inlineCode('5')} | External toolchain or Fastly local-execution failure. |

${inlineCode('pulse doctor')} completes with exit ${inlineCode('1')} when its audit contains failed checks. ${inlineCode('pulse test')} completes with exit ${inlineCode('1')} when a normal test run has failed cases. Setup failures use their diagnostic exit class.

Failed commands emit stable codes, categories, summaries, remediation, exit classes, and a versioned documentation URL. See [Diagnostics and remediation](diagnostics.md).
`);
}

