function expectedManifest(entry) {
  const file = path.join(repoRoot, entry.dir, 'package.json');
  const manifest = readJson(file);
  manifest.repository = Object.freeze({ type: REPOSITORY.type, url: REPOSITORY.url, directory: entry.dir });
  manifest.homepage = documentationUrl(entry.documentation);
  manifest.bugs = Object.freeze({ url: REPOSITORY.bugs });
  const files = [...(manifest.files || [])];
  if (entry.role === 'public-runtime' && !files.includes('docs')) files.push('docs');
  if (entry.role === 'public-cli') {
    for (const name of ['docs', 'examples', 'API.md', 'CHANGELOG.md']) if (!files.includes(name)) files.push(name);
  }
  manifest.files = files;
  return stableJson(manifest);
}

