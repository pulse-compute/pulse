function synchronizeReferenceDocs(options = {}) {
  const write = options.write === true;
  const ownership = synchronizeDocumentationMetadata({ repoRoot, write });
  const expected = buildExpectedFiles();
  const mismatches = [];
  let changedFiles = 0;

  for (const [relativeFile, rawContent] of expected) {
    const file = path.join(repoRoot, relativeFile);
    const content = Buffer.isBuffer(rawContent) ? rawContent : Buffer.from(stable(rawContent));
    const actual = fs.existsSync(file) ? fs.readFileSync(file) : undefined;
    if (!actual || !actual.equals(content)) {
      mismatches.push(relativeFile);
      if (write) {
        fs.mkdirSync(path.dirname(file), { recursive: true });
        fs.writeFileSync(file, content);
        changedFiles += 1;
      }
    }
  }

  const expectedNames = new Set(expected.keys());
  const extras = [];
  for (const rootRelative of generatedRoots()) {
    const root = path.join(repoRoot, rootRelative);
    for (const file of filesUnder(root)) {
      const name = relative(file);
      if (!expectedNames.has(name)) {
        extras.push(name);
        if (write) fs.rmSync(file, { force: true });
      }
    }
  }

  if (!write && (mismatches.length || extras.length)) {
    throw new Error(`generated documentation is stale. Run node wasm/scripts/sync-reference-docs.cjs --write. Mismatches: ${mismatches.join(', ') || 'none'}; extras: ${extras.join(', ') || 'none'}`);
  }

  return Object.freeze({
    status: 'ok',
    expectedFiles: expected.size,
    changedFiles,
    mismatches: Object.freeze(mismatches),
    removedExtras: Object.freeze(extras),
    ownership
  });
}

function main() {
  const args = new Set(process.argv.slice(2));
  const unknown = [...args].filter((arg) => !['--write', '--check', '--json'].includes(arg));
  if (unknown.length) {
    process.stderr.write(`Unknown option(s): ${unknown.join(', ')}\n`);
    process.exitCode = 2;
    return;
  }
  try {
    const result = synchronizeReferenceDocs({ write: args.has('--write') });
    if (args.has('--json')) process.stdout.write(stableJson(result));
    else process.stdout.write(`ok - ${result.expectedFiles} generated documentation/package file(s) are synchronized${result.changedFiles ? `; updated ${result.changedFiles}` : ''}\n`);
  } catch (error) {
    process.stderr.write(`${error && error.stack ? error.stack : String(error)}\n`);
    process.exitCode = 1;
  }
}

