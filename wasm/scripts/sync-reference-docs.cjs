function renderStatusBlock(entry, manifest) {
  const tier = SUPPORT_TIERS[entry.tier];
  const entryPoints = entry.entryPoints.map(inlineCode).join(', ');
  return [
    STATUS_START,
    `> **Support tier:** ${tier.label}<br>`,
    `> **Audience:** ${entry.audience}<br>`,
    `> **Install directly:** ${entry.directInstall}<br>`,
    `> **Supported entry points:** ${entryPoints}<br>`,
    `> **Stability:** ${entry.stability}<br>`,
    ...(entry.replacement ? [`> **Canonical replacement:** ${inlineCode(entry.replacement)}<br>`] : []),
    `> **Canonical documentation:** [Package guide](${publicCliDoc(entry.documentation)})`,
    '>',
    `> This release-status block is generated from the synchronized ${inlineCode(`Pulse ${RELEASE_VERSION}`)} package policy.`,
    STATUS_END
  ].join('\n');
}

function withStatusBlock(source, entry, manifest) {
  const block = renderStatusBlock(entry, manifest);
  const existing = new RegExp(`${STATUS_START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${STATUS_END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*`);
  if (existing.test(source)) return stable(source.replace(existing, `${block}\n\n`));
  const match = /^# [^\r\n]+\r?\n/.exec(source);
  if (!match) throw new Error(`${entry.dir}/README.md must begin with one H1`);
  return stable(`${match[0]}\n${block}\n\n${source.slice(match[0].length).replace(/^\s+/, '')}`);
}

function renderPackagePolicy() {
  const rows = PACKAGE_SET.map((entry) => {
    const manifest = packageManifest(entry);
    const tier = SUPPORT_TIERS[entry.tier];
    const direct = entry.directInstall.startsWith('Yes') ? 'Yes' : 'No';
    const guide = `./${path.basename(entry.documentation)}`;
    return `| [${inlineCode(manifest.name)}](${guide}) | ${tier.label} | ${direct} | ${entry.stability} |`;
  });
  return stable(`# Package support policy

${GENERATED_NOTICE}

Pulse ${RELEASE_VERSION} publishes one synchronized ${PACKAGE_SET.length}-package release set. Publication does not make every package an application-author SDK: the support tier and listed entry points define the release promise.

| Package | Support tier | Install directly | Release promise |
|---|---|---:|---|
${rows.join('\n')}

## Tier definitions

${Object.values(SUPPORT_TIERS).map((tier) => `### ${tier.label}\n\n${tier.promise}`).join('\n\n')}

## Reading package READMEs

Every packed README begins with a generated status block covering audience, direct-install guidance, supported entry points, and stability. An export that is not listed in that block is not automatically a supported application-author entry point.

## Extension and provider boundary in ${RELEASE_VERSION}

Pulse supports the documented package-owned assets and GRIP facades and the documented Fastly provider entry points. Their implementation demonstrates the internal contract, but ${inlineCode(RELEASE_VERSION)} does **not** expose a general third-party plugin registry:

- lowerer manifests are accepted only from trusted first-party release packages;
- arbitrary external lowerer discovery and execution are not supported;
- provider selection is limited to ${inlineCode('node')}, ${inlineCode('fastly')}, and compile-only ${inlineCode('none')};
- adding a new lowerer or provider currently means changing and testing the synchronized Pulse release set.

Documentation may explain lowering and the internal contract, but it must not promise that an external npm package can self-register a lowerer or provider. A future public plugin API requires an explicit trust model, discovery, version negotiation, security policy, and compatibility contract.

## Installed documentation

${inlineCode('@pulse-compute/runtime')} ships its canonical API reference and Beta scope. ${inlineCode('@pulse-compute/cli')} ships the public documentation hierarchy, CLI/config/diagnostic references, bounded compatibility material, and runnable example sources. Package README links must resolve either inside their own tarball or to an exact-version hosted Pulse documentation URL.
`);
}


