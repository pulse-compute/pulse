export function matchFirstRouteRuntimeId(methodCode: i32, requestPath: string): i32 {
  const normalizedPath = normalizeRequestPath(requestPath)
  let index = scanNextEntry(0, MODE_NORMAL, methodCode, normalizedPath)
  while (index >= 0) {
    if (entryKindAt(index) == ENTRY_ROUTE) return entryRouteRuntimeIdAt(index)
    index = scanNextEntry(entryNextIndexAt(index), MODE_NORMAL, methodCode, normalizedPath)
  }
  return -1
}

