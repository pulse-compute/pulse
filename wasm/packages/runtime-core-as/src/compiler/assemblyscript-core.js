function sha256(text) {
  return crypto.createHash('sha256').update(text, 'utf8').digest('hex');
}

function makeFile(file, text) {
  return {
    file,
    bytes: Buffer.byteLength(text, 'utf8'),
    sha256: sha256(text),
    text
  };
}

function asString(value) {
  return JSON.stringify(String(value ?? ''));
}

function safeIdentifier(value, fallback = 'handler') {
  const raw = String(value || fallback).replace(/[^A-Za-z0-9_$]/g, '_');
  const cleaned = raw.length > 0 ? raw : fallback;
  return /^[A-Za-z_$]/.test(cleaned) ? cleaned : `_${cleaned}`;
}

function handlerBaseRole(slot) {
  return String((slot?.roles || [])[0] || '').split(':')[0] || 'unknown';
}

function handlerExternalName(slot) {
  return `__pulsewasm_handler_${Number(slot.slot) | 0}_${safeIdentifier(slot.name || slot.id || 'handler')}`;
}

function handlerExternalField(slot) {
  return String(slot.exportName || slot.name || slot.id || `handler_${slot.slot}`);
}

function sortHandlerSlots(dispatchTable) {
  return (dispatchTable?.handlerSlots || []).slice().sort((a, b) => Number(a.slot) - Number(b.slot));
}

