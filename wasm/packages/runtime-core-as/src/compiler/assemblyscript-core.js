export function normalizeRequestPath(input: string): string {
  let path = input.length == 0 ? '/' : input
  if (path.charCodeAt(0) != SLASH) path = '/' + path
  while (path.length > 1 && path.charCodeAt(path.length - 1) == SLASH) {
    path = path.substring(0, path.length - 1)
  }
  return path
}

export function requestPathIsValid(input: string): bool {
  const path = normalizeRequestPath(input)
  if (path.length == 0) return false
  if (path.charCodeAt(0) != SLASH) return false
  for (let i: i32 = 1; i < path.length; i++) {
    if (path.charCodeAt(i) == SLASH && path.charCodeAt(i - 1) == SLASH) return false
  }
  return true
}

function hasLeadingSlash(path: string): bool {
  return path.length > 0 && path.charCodeAt(0) == SLASH
}

export function pathSegmentCount(input: string): i32 {
  const path = normalizeRequestPath(input)
  if (!requestPathIsValid(path)) return -1
  let count: i32 = 0
  let start: i32 = hasLeadingSlash(path) ? 1 : 0
  const length: i32 = path.length
  if (length == 1) return 0
  for (let i: i32 = start; i <= length; i++) {
    if (i == length || path.charCodeAt(i) == SLASH) {
      if (i <= start) return -1
      count++
      start = i + 1
    }
  }
  return count
}

export function pathSegmentStartAt(input: string, targetIndex: i32): i32 {
  if (targetIndex < 0) return -1
  const path = normalizeRequestPath(input)
  if (!requestPathIsValid(path)) return -1
  let current: i32 = 0
  let start: i32 = hasLeadingSlash(path) ? 1 : 0
  const length: i32 = path.length
  if (length == 1) return -1
  for (let i: i32 = start; i <= length; i++) {
    if (i == length || path.charCodeAt(i) == SLASH) {
      if (i <= start) return -1
      if (current == targetIndex) return start
      current++
      start = i + 1
    }
  }
  return -1
}

export function pathSegmentEndAt(input: string, targetIndex: i32): i32 {
  if (targetIndex < 0) return -1
  const path = normalizeRequestPath(input)
  if (!requestPathIsValid(path)) return -1
  let current: i32 = 0
  let start: i32 = hasLeadingSlash(path) ? 1 : 0
  const length: i32 = path.length
  if (length == 1) return -1
  for (let i: i32 = start; i <= length; i++) {
    if (i == length || path.charCodeAt(i) == SLASH) {
      if (i <= start) return -1
      if (current == targetIndex) return i
      current++
      start = i + 1
    }
  }
  return -1
}

export function pathSegmentLengthAt(input: string, targetIndex: i32): i32 {
  const start = pathSegmentStartAt(input, targetIndex)
  if (start < 0) return -1
  const end = pathSegmentEndAt(input, targetIndex)
  if (end < start) return -1
  return end - start
}

export function pathSegmentAt(input: string, targetIndex: i32): string {
  const path = normalizeRequestPath(input)
  const start = pathSegmentStartAt(path, targetIndex)
  if (start < 0) return ''
  const end = pathSegmentEndAt(path, targetIndex)
  if (end < start) return ''
  return path.substring(start, end)
}

