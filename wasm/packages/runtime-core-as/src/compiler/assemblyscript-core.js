function buildHandlerSlotsSource(dispatchTable) {
  const slots = sortHandlerSlots(dispatchTable);
  const declarations = [];
  const routeCases = [];
  const middlewareCases = [];
  const lifecycleCases = [];
  const errorCases = [];
  const channelCases = [];

  for (const slot of slots) {
    const role = handlerBaseRole(slot);
    const fn = handlerExternalName(slot);
    const field = handlerExternalField(slot);
    const slotNumber = Number(slot.slot) | 0;

    if (role === 'error') {
      declarations.push(`@external("pulsewasm_handlers", ${asString(field)})\ndeclare function ${fn}(err: usize, ctx: usize, next: usize): void`);
      errorCases.push(`    case ${slotNumber}: ${fn}(err, ctx, next); return true`);
    } else if (role === 'channel') {
      declarations.push(`@external("pulsewasm_handlers", ${asString(field)})\ndeclare function ${fn}(ctx: usize): usize`);
      channelCases.push(`    case ${slotNumber}: return ${fn}(ctx)`);
    } else if (role === 'lifecycle') {
      declarations.push(`@external("pulsewasm_handlers", ${asString(field)})\ndeclare function ${fn}(ctx: usize, next: usize): void`);
      lifecycleCases.push(`    case ${slotNumber}: ${fn}(ctx, next); return true`);
    } else if (role === 'middleware') {
      declarations.push(`@external("pulsewasm_handlers", ${asString(field)})\ndeclare function ${fn}(ctx: usize, next: usize): void`);
      middlewareCases.push(`    case ${slotNumber}: ${fn}(ctx, next); return true`);
    } else if (role === 'route') {
      declarations.push(`@external("pulsewasm_handlers", ${asString(field)})\ndeclare function ${fn}(ctx: usize, next: usize): void`);
      routeCases.push(`    case ${slotNumber}: ${fn}(ctx, next); return true`);
    }
  }

  const declarationText = declarations.length > 0 ? declarations.join('\n\n') : '// No handler slots were emitted.';
  const routeCaseText = routeCases.length > 0 ? routeCases.join('\n') : '';
  const middlewareCaseText = middlewareCases.length > 0 ? middlewareCases.join('\n') : '';
  const lifecycleCaseText = lifecycleCases.length > 0 ? lifecycleCases.join('\n') : '';
  const errorCaseText = errorCases.length > 0 ? errorCases.join('\n') : '';
  const channelCaseText = channelCases.length > 0 ? channelCases.join('\n') : '';

  return `${header()}import {
  ROLE_ROUTE,
  ROLE_MIDDLEWARE,
  ROLE_LIFECYCLE,
  ROLE_ERROR,
  ROLE_CHANNEL
} from './types.as'

import {
  HANDLER_SLOT_COUNT,
  HANDLER_SLOT_IDS,
  HANDLER_SLOT_NAMES,
  HANDLER_ROLE_CODES,
  HANDLER_PARAM_COUNTS
} from './route-table.as'

// Phase 9C handler slot declarations.
// These are AssemblyScript import declarations. They bind dense handler slots to
// externally supplied/linked handler functions without re-reading user source.
${declarationText}

export const HANDLER_BINDINGS_MODULE: string = 'pulsewasm_handlers'
export const HANDLER_BINDING_COUNT: i32 = HANDLER_SLOT_COUNT

export function handlerSlotExists(slot: i32): bool {
  return slot >= 0 && slot < HANDLER_SLOT_COUNT
}

export function handlerIdForSlot(slot: i32): string {
  if (!handlerSlotExists(slot)) return ''
  return unchecked(HANDLER_SLOT_IDS[slot])
}

export function handlerNameForSlot(slot: i32): string {
  if (!handlerSlotExists(slot)) return ''
  return unchecked(HANDLER_SLOT_NAMES[slot])
}

export function handlerRoleCodeForSlot(slot: i32): i32 {
  if (!handlerSlotExists(slot)) return 0
  return unchecked(HANDLER_ROLE_CODES[slot])
}

export function handlerParamCountForSlot(slot: i32): i32 {
  if (!handlerSlotExists(slot)) return -1
  return unchecked(HANDLER_PARAM_COUNTS[slot])
}

export function slotAcceptsRole(slot: i32, roleCode: i32): bool {
  return handlerSlotExists(slot) && handlerRoleCodeForSlot(slot) == roleCode
}

export function invokeRouteHandlerBySlot(slot: i32, ctx: usize, next: usize): bool {
  if (!slotAcceptsRole(slot, ROLE_ROUTE)) return false
  switch (slot) {
${routeCaseText}
    default: return false
  }
}

export function invokeMiddlewareHandlerBySlot(slot: i32, ctx: usize, next: usize): bool {
  if (!slotAcceptsRole(slot, ROLE_MIDDLEWARE)) return false
  switch (slot) {
${middlewareCaseText}
    default: return false
  }
}

export function invokeLifecycleHandlerBySlot(slot: i32, ctx: usize, next: usize): bool {
  if (!slotAcceptsRole(slot, ROLE_LIFECYCLE)) return false
  switch (slot) {
${lifecycleCaseText}
    default: return false
  }
}

export function invokeErrorHandlerBySlot(slot: i32, err: usize, ctx: usize, next: usize): bool {
  if (!slotAcceptsRole(slot, ROLE_ERROR)) return false
  switch (slot) {
${errorCaseText}
    default: return false
  }
}

export function invokeChannelHandlerBySlot(slot: i32, ctx: usize): usize {
  if (!slotAcceptsRole(slot, ROLE_CHANNEL)) return 0
  switch (slot) {
${channelCaseText}
    default: return 0
  }
}

export function invokeHandlerByRole(roleCode: i32, slot: i32, err: usize, ctx: usize, next: usize): bool {
  if (roleCode == ROLE_ROUTE) return invokeRouteHandlerBySlot(slot, ctx, next)
  if (roleCode == ROLE_MIDDLEWARE) return invokeMiddlewareHandlerBySlot(slot, ctx, next)
  if (roleCode == ROLE_LIFECYCLE) return invokeLifecycleHandlerBySlot(slot, ctx, next)
  if (roleCode == ROLE_ERROR) return invokeErrorHandlerBySlot(slot, err, ctx, next)
  if (roleCode == ROLE_CHANNEL) return invokeChannelHandlerBySlot(slot, ctx) != 0
  return false
}
`;
}

