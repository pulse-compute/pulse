function writeStagedFiles(stagingDir, shape, core, schemaJsonSidecar, librarySidecars, files) {
  const byFile = new Map();
  for (const file of (shape?.files || [])) byFile.set(file.file, file.text);
  for (const file of (core?.files || [])) byFile.set(file.file, file.text);
  for (const file of (schemaJsonSidecar?.files || [])) if (file.file.startsWith('generated/as/schema-json/')) byFile.set(file.file, file.text);
  for (const file of (librarySidecars?.files || [])) if (file.file.startsWith('generated/as/library-sidecars/')) byFile.set(file.file, file.text);
  for (const file of files) byFile.set(file.file, file.text);
  for (const [file, text] of byFile.entries()) {
    const abs = path.join(stagingDir, file);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, text, 'utf8');
  }
  return Array.from(byFile.entries()).map(([file, text]) => ({ file, bytes: Buffer.byteLength(text, 'utf8'), sha256: sha256Text(text) }));
}

function compileAndSmoke({ cwd, outDir, shape, core, schemaJsonSidecar, librarySidecars, files }) {
  const diagnostics = [];
  const asc = resolveAsc(cwd);
  if (!asc) {
    diagnostics.push(diagnostic('PULSEWASM_INTEGRATED_ASC_MISSING', 'AssemblyScript compiler dependency was not found.', 'Run npm install before the integrated compiled app smoke.'));
    return { diagnostics, outputs: [], warnings: [], smoke: undefined };
  }
  const stagingDir = fs.mkdtempSync(path.join(os.tmpdir(), 'pulsewasm-integrated-compiled-app-'));
  const outputDir = path.join(outDir || getDefaultArtifactsDir(cwd), 'generated', 'integrated-compiled-app');
  fs.mkdirSync(outputDir, { recursive: true });
  const staged = writeStagedFiles(stagingDir, shape, core, schemaJsonSidecar, librarySidecars, files);
  const wasmFile = path.join(outputDir, 'pulsewasm-integrated-compiled-app.wasm');
  const watFile = path.join(outputDir, 'pulsewasm-integrated-compiled-app.wat');
  const entry = path.join(stagingDir, 'generated/as-smoke/integrated-compiled-app-smoke-runner.as.ts');
  const ascArgs = [asc.script, entry, '--outFile', wasmFile, '--textFile', watFile, '--runtime', 'stub', '--noAssert'];
  const proc = spawnSync(asc.executable, ascArgs, { cwd, encoding: 'utf8', maxBuffer: 1024 * 1024 * 16 });
  const warnings = parseAscWarnings(proc.stderr);
  if (proc.error || proc.status !== 0) diagnostics.push(diagnostic('PULSEWASM_INTEGRATED_AS_COMPILE_FAILED', `Integrated compiled app AssemblyScript smoke failed${proc.status !== undefined ? ` with exit code ${proc.status}` : ''}.`, 'Inspect integrated-compiled-app-smoke.json stderr/stdout.', { stdout: truncate(proc.stdout), stderr: truncate(proc.stderr), exitCode: proc.status }));
  const outputFiles = [];
  if (fs.existsSync(wasmFile)) outputFiles.push(fileRecord(wasmFile, cwd, 'integrated-compiled-app-wasm'));
  if (fs.existsSync(watFile)) outputFiles.push(fileRecord(watFile, cwd, 'integrated-compiled-app-wat'));
  let smoke;
  if (diagnostics.length === 0 && fs.existsSync(wasmFile)) {
    try {
      const wasm = fs.readFileSync(wasmFile);
      const module = new WebAssembly.Module(wasm);
      const instance = new WebAssembly.Instance(module, { env: { abort() { throw new Error('AssemblyScript abort'); } } });
      const checkDefs = [
        ['smoke_integrated_schema_status', 201], ['smoke_integrated_schema_body', 1], ['smoke_integrated_schema_kind', 1],
        ['smoke_integrated_schema_error_status', 400], ['smoke_integrated_schema_error_body', 1],
        ['smoke_integrated_extension_status', 220], ['smoke_integrated_extension_body', 1], ['smoke_integrated_extension_mark_count', 1],
        ['smoke_integrated_stream_status', 206], ['smoke_integrated_stream_kind', 1], ['smoke_integrated_stream_response_ref', 1], ['smoke_integrated_stream_header', 1], ['smoke_integrated_stream_repeated_header', 1]
      ];
      const checks = [];
      for (const [name, expected] of checkDefs) {
        let actual; let status = 'ok'; let message;
        try {
          const fn = instance.exports[name];
          if (typeof fn !== 'function') { status = 'error'; message = 'Missing smoke export.'; }
          else { actual = fn(); if (actual !== expected) { status = 'error'; message = `Expected ${expected}, got ${actual}.`; } }
        } catch (error) { status = 'error'; message = error && error.message ? error.message : String(error); }
        checks.push({ name, expected, actual, status, message });
      }
      smoke = { imports: WebAssembly.Module.imports(module), exports: WebAssembly.Module.exports(module), checks, failedChecks: checks.filter((check) => check.status !== 'ok'), wasmBytes: wasm.length };
      if (smoke.failedChecks.length) diagnostics.push(diagnostic('PULSEWASM_INTEGRATED_SMOKE_FAILED', 'Integrated compiled app smoke checks failed.', 'Inspect integrated-compiled-app-smoke.json checks.', { failedChecks: smoke.failedChecks }));
    } catch (error) { diagnostics.push(diagnostic('PULSEWASM_INTEGRATED_SMOKE_EXECUTION_FAILED', 'Integrated compiled app smoke execution failed.', undefined, { message: error && error.message ? error.message : String(error), stack: error && error.stack ? error.stack : undefined })); }
  }
  return { diagnostics, warnings, smoke, outputFiles, staged, command: { executable: asc.display, args: ascArgs.slice(1).map((arg) => path.isAbsolute(arg) ? path.relative(cwd, arg).replace(/\\/g, '/') : arg) }, result: { exitCode: proc.status, stdout: truncate(proc.stdout), stderr: truncate(proc.stderr) } };
}

