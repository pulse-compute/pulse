'use strict';

const { PACKAGE_VERSION, normalizeArtifact } = require('@pulse-compute/wasm-contracts/diagnostics');
const {
  REQUEST_RESULT_HEADERS_VERSION,
  REQUEST_RESULT_HEADERS_PHASE,
  HEADER_ABI_EXPORTS,
  handlerVisibleHeaderAbiExports,
  hostResultHeaderAbiExports
} = loadContractsRequestResultHeaders();

function loadContractsRequestResultHeaders() {
  try {
    return require('@pulse-compute/wasm-contracts/host/request-result-headers');
  } catch (error) {
    if (error && error.code === 'MODULE_NOT_FOUND' && String(error.message).includes('@pulse-compute/wasm-contracts')) {
      return require('../../../contracts/src/host/request-result-headers.js');
    }
    throw error;
  }
}

function buildMarkdown(artifact) {
  const lines = [];
  lines.push('# PulseWasm Request / Result / Headers Adaptor Contract v1');
  lines.push('');
  lines.push(`Generated by: \`${artifact.generatedBy}\``);
  lines.push(`Phase: \`${artifact.policy.phase}\``);
  lines.push('');
  lines.push('## Locked positions');
  lines.push('');
  for (const item of artifact.lockedPositions) lines.push(`- ${item}`);
  lines.push('');
  lines.push('## Header storage');
  lines.push('');
  lines.push('- ordered entries preserve original output order');
  lines.push('- repeated headers are preserved, not collapsed');
  lines.push('- lookup is ASCII case-insensitive through a lowercase index key');
  lines.push('- request headers are read-only to handlers');
  lines.push('- response headers are mutable through set / append / delete');
  lines.push('');
  lines.push('## Handler-visible ABI');
  lines.push('');
  for (const item of artifact.abi.handlerVisibleExports) lines.push(`- \`${item}\``);
  lines.push('');
  lines.push('## Host result header iteration');
  lines.push('');
  for (const item of artifact.abi.hostResultHeaderExports) lines.push(`- \`${item}\``);
  lines.push('');
  lines.push('## Body policy');
  lines.push('');
  lines.push(`- Request body: \`${artifact.bodyPolicy.requestBody}\``);
  lines.push(`- Response body: \`${artifact.bodyPolicy.responseBody}\``);
  lines.push(`- JSON: \`${artifact.bodyPolicy.json}\``);
  lines.push(`- Binary: \`${artifact.bodyPolicy.binary}\``);
  lines.push('');
  lines.push('## GRIP / broadcaster note');
  lines.push('');
  lines.push('GRIP/Fanout framing is expressed through normal response headers. The later broadcaster/GRIP adaptor inspects headers such as `Grip-Hold` and repeated `Grip-Channel` entries.');
  lines.push('');
  return `${lines.join('\n')}\n`;
}

function buildRequestResultHeaders(dispatchTable, executionPlan, options = {}) {
  const cwd = options.cwd || process.cwd();
  const generatedBy = options.generatedBy || PACKAGE_VERSION;
  const artifact = normalizeArtifact({
    version: REQUEST_RESULT_HEADERS_VERSION,
    generatedBy,
    source: dispatchTable?.source,
    policy: {
      phase: REQUEST_RESULT_HEADERS_PHASE,
      status: 'locked-contract-and-local-bridge-proof',
      sourceOfTruth: [
        'wasm-host-abi.json',
        'wasm-host-bridge.json',
        'pulsewasm request/result/headers adaptor contract v1'
      ],
      headersFirstClass: true,
      bodyDeferred: true,
      platformBindings: false,
      witBindings: false,
      jsonBodyAbi: false,
      binaryBodyAbi: false,
      streamBodyAbi: true
    },
    lockedPositions: [
      'Headers are first-class runtime artifacts.',
      'Header storage is ordered, repeated, and case-insensitive for lookup.',
      'Request headers are read-only to handlers.',
      'Response headers are mutable through set / append / delete.',
      'Header export preserves repeated headers and original order.',
      'GRIP/Fanout framing is expressed through normal response headers.',
      'Request body is lazy/deferred.',
      'Text, JSON text, empty, and stream response bodies are implemented; binary buffers remain reserved.'
    ],
    headerStorage: {
      entry: { name: 'string', lowerName: 'string', value: 'string' },
      ordered: true,
      repeated: true,
      lookup: 'ASCII case-insensitive lowerName scan; future implementation may add index arrays',
      request: { mutability: 'host-seeded read-only to handlers' },
      response: { mutability: 'handler mutable', operations: ['set', 'append', 'delete'] }
    },
    abi: {
      handlerVisibleExports: handlerVisibleHeaderAbiExports(),
      hostResultHeaderExports: hostResultHeaderAbiExports(),
      allExports: HEADER_ABI_EXPORTS
    },
    grip: {
      modeledAsHeaders: true,
      importantHeaders: ['Grip-Hold', 'Grip-Channel'],
      repeatedGripChannelPreserved: true,
      silentIgnoreForbidden: true
    },
    bodyPolicy: {
      requestBody: 'deferred; no automatic read, no parse-on-dispatch',
      responseBody: 'RESULT_TEXT, RESULT_JSON, RESULT_EMPTY, and RESULT_STREAM; RESULT_BINARY reserved',
      json: 'RESULT_JSON declared/reserved, not lowered in 10D',
      binary: 'RESULT_BINARY declared/reserved; RESULT_STREAM is the primary payload pass-through primitive'
    },
    summary: {
      routes: Array.isArray(dispatchTable?.routes) ? dispatchTable.routes.length : 0,
      executionEntries: Array.isArray(executionPlan?.entries) ? executionPlan.entries.length : 0,
      headerAbiExports: HEADER_ABI_EXPORTS.length,
      requestHeaderReadExports: 3,
      responseHeaderWriteExports: 3,
      resultHeaderIterationExports: 5,
      repeatedHeadersPreserved: true,
      gripHeadersModeled: true,
      requestBodyDeferred: true,
      responseTextAndEmptyOnly: false,
      streamResultImplemented: true,
      binaryReserved: true
    }
  }, cwd);

  return {
    artifact,
    files: [
      {
        file: 'generated/host/request-result-headers.md',
        text: buildMarkdown(artifact)
      }
    ],
    diagnostics: []
  };
}

module.exports = {
  REQUEST_RESULT_HEADERS_VERSION,
  buildRequestResultHeaders
};
