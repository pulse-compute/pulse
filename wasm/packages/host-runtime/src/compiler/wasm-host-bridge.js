function sha256Buffer(buffer) { return crypto.createHash('sha256').update(buffer).digest('hex'); }
function sha256Text(text) { return crypto.createHash('sha256').update(text, 'utf8').digest('hex'); }
function stripAnsi(value) { return String(value || '').replace(/\u001b\[[0-9;]*m/g, ''); }

function parseAscWarnings(stderr) {
  const text = stripAnsi(stderr);
  const warnings = [];
  const regex = /WARNING\s+(AS\d+):\s+([^\n]+)(?:.|\n)*?in ([^\n]+)\((\d+),(\d+)\)/g;
  let match;
  while ((match = regex.exec(text))) {
    warnings.push({ code: match[1], message: match[2].trim(), file: match[3], line: Number(match[4]), column: Number(match[5]) });
  }
  if (warnings.length === 0 && /WARNING\s+AS\d+:/m.test(text)) {
    warnings.push({ code: 'AS_WARNING', message: 'AssemblyScript emitted one or more warnings. Inspect result.stderr for details.' });
  }
  return warnings;
}

