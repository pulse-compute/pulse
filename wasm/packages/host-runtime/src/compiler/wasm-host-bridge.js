function fileRecord(filePath, cwd, kind) {
  const buffer = fs.readFileSync(filePath);
  return { file: path.relative(cwd, filePath).replace(/\\/g, '/'), kind, bytes: buffer.length, sha256: sha256Buffer(buffer) };
}

function writeStagedFiles(stagingDir, shape, core, bridgeRunnerText) {
  const allFiles = [];
  if (shape && Array.isArray(shape.files)) allFiles.push(...shape.files);
  if (core && Array.isArray(core.files)) allFiles.push(...core.files);
  const byFile = new Map();
  for (const file of allFiles) byFile.set(file.file, file.text);
  byFile.set(BRIDGE_RUNNER_FILE, bridgeRunnerText);
  for (const [file, text] of byFile.entries()) {
    const abs = path.join(stagingDir, file);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, text, 'utf8');
  }
  return Array.from(byFile.entries()).map(([file, text]) => ({ file, bytes: Buffer.byteLength(text, 'utf8'), sha256: sha256Text(text) }));
}

