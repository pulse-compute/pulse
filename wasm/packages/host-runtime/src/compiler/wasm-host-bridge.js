function maybeBroadcastForState(state: PulseWasmDispatchState): void {
  const scopeId = state.currentScopeId
  if (scopeId < 0) return
  if (scopeChannelKind(scopeId) != CHANNEL_HANDLER) return
  const slot = scopeChannelSlot(scopeId)
  if (slot < 0) return
  const channelsRef = invokeChannelHandler(slot, changetype<usize>(state))
  if (channelsRef == 0) return
  __lastChannelsRef = channelsRef
  const result = __pulsewasm_broadcast(channelsRef, changetype<usize>(state))
  __lastBroadcastResult = result
  if (result != 0) setErrorResult(HOST_BRIDGE_INTERNAL_ERROR, result)
}

function executeState(state: PulseWasmDispatchState): i32 {
  __currentState = state
  let guard: i32 = 0
  while (guard < EXECUTION_ENTRY_COUNT + 16) {
    guard += 1
    const step = stepDispatchState(state)
    if (step == STEP_INVOKE) {
      __lastInvokedHandlers += 1
      const invoked = invokeCurrentHandler(state)
      if (!invoked) {
        setErrorResult(HOST_BRIDGE_INTERNAL_ERROR, changetype<usize>(createPulseWasmError('PULSEWASM_HANDLER_NOT_BOUND', 'Handler slot could not be invoked.', HOST_BRIDGE_INTERNAL_ERROR)))
        return __resultStatus
      }
      if (__resultStatus != 0 || __resultKind != RESULT_NONE) {
        maybeBroadcastForState(state)
        return __resultStatus
      }
      if (state.nextOutcome == NEXT_NORMAL || state.nextOutcome == NEXT_ERROR) continue
      setErrorResult(HOST_BRIDGE_INTERNAL_ERROR, changetype<usize>(createPulseWasmError('PULSEWASM_NO_RESULT', 'Handler halted without result or continuation.', HOST_BRIDGE_INTERNAL_ERROR)))
      return __resultStatus
    }
    if (step == STEP_NOT_FOUND) { setEmptyResult(404); return __resultStatus }
    if (step == STEP_UNHANDLED_ERROR) { setErrorResult(500, state.activeError); return __resultStatus }
    if (step == STEP_CONTRACT_VIOLATION) {
      setErrorResult(500, changetype<usize>(createPulseWasmError('PULSEWASM_NO_RESULT', 'Handler halted without result or continuation.', 500)))
      return __resultStatus
    }
    const fallback = defaultStatusForStepResult(step)
    if (fallback != 0) { setEmptyResult(fallback); return __resultStatus }
    setErrorResult(500, changetype<usize>(createPulseWasmError('PULSEWASM_INVALID_STEP', 'Invalid routing step result.', 500)))
    return __resultStatus
  }
  setErrorResult(500, changetype<usize>(createPulseWasmError('PULSEWASM_DISPATCH_GUARD_EXHAUSTED', 'Dispatch guard exhausted.', 500)))
  return __resultStatus
}

function findScopeForPath(methodCode: i32, requestPath: string): PulseWasmDispatchState {
  const state = createDispatchState(methodCode, requestPath)
  let guard: i32 = 0
  while (guard < EXECUTION_ENTRY_COUNT + 16) {
    guard += 1
    const step = stepDispatchState(state)
    if (step != STEP_INVOKE) return state
    if (state.currentKind == ENTRY_ROUTE) return state
    continueNormal(state)
  }
  return state
}

function executeLifecycleForScope(state: PulseWasmDispatchState, eventKind: i32): i32 {
  __currentState = state
  let invoked: i32 = 0
  const scopeId = state.currentScopeId
  const length = eventKind == 1 ? scopeConnectLength(scopeId) : scopeDisconnectLength(scopeId)
  for (let i: i32 = 0; i < length; i += 1) {
    const slot = eventKind == 1 ? scopeConnectSlotAt(scopeId, i) : scopeDisconnectSlotAt(scopeId, i)
    if (slot >= 0 && invokeLifecycleHandler(slot, changetype<usize>(state), changetype<usize>(state))) invoked += 1
  }
  return invoked
}

