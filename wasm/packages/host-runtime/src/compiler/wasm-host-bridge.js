function lowerAscii(value: string): string {
  let out = ''
  for (let i: i32 = 0; i < value.length; i += 1) {
    let code = value.charCodeAt(i)
    if (code >= 65 && code <= 90) code += 32
    out += String.fromCharCode(code)
  }
  return out
}

