function ascExecutable(cwd) {
  try {
    const ascPath = require.resolve('assemblyscript/bin/asc.js', { paths: [cwd] });
    return { command: process.execPath, argsPrefix: [ascPath], display: `node ${path.relative(cwd, ascPath).replace(/\\/g, '/')}` };
  } catch (_) {
    return undefined;
  }
}

function compileBridge(stagingDir, cwd, options = {}) {
  const asc = ascExecutable(cwd);
  if (!asc) {
    return {
      asc,
      result: { status: 1, stdout: '', stderr: 'assemblyscript package is not installed.' },
      diagnostics: [diagnosticFromParts({
        phase: 'wasm-host-bridge',
        code: 'PULSEWASM_ASSEMBLYSCRIPT_NOT_INSTALLED',
        message: 'AssemblyScript is required for Phase 10D Wasm host bridge compilation.',
        hint: 'Run npm install before requesting --emit-wasm-host-bridge or --emit-request-result-headers.'
      })]
    };
  }

  const outDir = options.outDir ? path.resolve(cwd, options.outDir) : getDefaultArtifactsDir(cwd);
  const wasmFile = path.join(outDir, BRIDGE_WASM_REL);
  const watFile = path.join(outDir, BRIDGE_WAT_REL);
  fs.mkdirSync(path.dirname(wasmFile), { recursive: true });
  fs.mkdirSync(path.dirname(watFile), { recursive: true });
  const input = path.join(stagingDir, BRIDGE_RUNNER_FILE);
  const args = [...asc.argsPrefix, input, '--outFile', wasmFile, '--textFile', watFile, '--runtime', 'stub', '--noAssert'];
  const started = Date.now();
  const result = spawnSync(asc.command, args, { cwd, encoding: 'utf8', maxBuffer: 1024 * 1024 * 20 });
  const durationMs = Date.now() - started;
  const warnings = parseAscWarnings(result.stderr || '');
  const diagnostics = [];
  if (result.error || result.status !== 0) {
    diagnostics.push(diagnosticFromParts({
      phase: 'wasm-host-bridge',
      code: 'PULSEWASM_WASM_HOST_BRIDGE_COMPILE_FAILED',
      message: 'Phase 10D Wasm host bridge compile failed.',
      hint: 'Inspect wasm-host-bridge.json result.stderr for AssemblyScript diagnostics.',
      details: { exitCode: result.status, stderr: result.stderr || '', stdout: result.stdout || '', error: result.error ? result.error.message : undefined }
    }));
  }
  if (warnings.length > 0) {
    diagnostics.push(diagnosticFromParts({
      phase: 'wasm-host-bridge',
      code: 'PULSEWASM_WASM_HOST_BRIDGE_WARNINGS',
      message: 'Phase 10D Wasm host bridge emitted AssemblyScript warnings.',
      hint: 'Warnings are treated as failures at this ABI boundary.',
      details: { warnings }
    }));
  }
  return { asc, args, wasmFile, watFile, durationMs, warnings, result, diagnostics };
}

function instantiateWithoutBroadcaster(wasmFile) {
  try {
    const wasm = fs.readFileSync(wasmFile);
    const module = new WebAssembly.Module(wasm);
    const importObject = { env: { abort() { throw new Error('abort'); } }, pulsewasm_handlers: {} };
    for (const imp of WebAssembly.Module.imports(module)) if (imp.module === 'pulsewasm_handlers') importObject.pulsewasm_handlers[imp.name] = () => 0;
    new WebAssembly.Instance(module, importObject);
    return { missingBroadcasterRejected: false, error: undefined };
  } catch (error) {
    return { missingBroadcasterRejected: true, error: error && error.message ? error.message : String(error) };
  }
}

function instantiateAndRunBridge(wasmFile) {
  const wasm = fs.readFileSync(wasmFile);
  const module = new WebAssembly.Module(wasm);
  const imports = WebAssembly.Module.imports(module);
  const exports = WebAssembly.Module.exports(module);
  let instance;
  const encoder = new TextEncoder();
  const decoder = new TextDecoder();
  const handlerCalls = {};
  const observedParams = {};
  const observedState = {};
  const observedHeaders = {};
  const broadcasterCalls = [];

  function memory() { return instance.exports.memory; }
  function allocBytes(text) {
    const bytes = encoder.encode(text);
    const ptr = instance.exports.pulse_alloc(bytes.length || 1);
    new Uint8Array(memory().buffer, ptr, bytes.length).set(bytes);
    return { ptr, len: bytes.length, text };
  }
  function readBytes(ptr, len) { return (!ptr || !len) ? '' : decoder.decode(new Uint8Array(memory().buffer, ptr, len)); }
  function readStringRef(ref) {
    if (!ref) return undefined;
    return readBytes(instance.exports.pulse_string_ptr(ref), instance.exports.pulse_string_len(ref));
  }
  function setResultText(ctx, status, body) {
    const encoded = allocBytes(body);
    instance.exports.pulse_result_text(ctx, status, encoded.ptr, encoded.len);
  }
  function getParam(ctx, name) {
    const encoded = allocBytes(name);
    return readStringRef(instance.exports.pulse_ctx_param(ctx, encoded.ptr, encoded.len));
  }
  function stateSet(ctx, key, value) {
    const k = allocBytes(key); const v = allocBytes(value);
    instance.exports.pulse_ctx_state_set(ctx, k.ptr, k.len, v.ptr, v.len);
  }
  function stateGet(ctx, key) {
    const k = allocBytes(key);
    return readStringRef(instance.exports.pulse_ctx_state_get(ctx, k.ptr, k.len));
  }
  function requestHeaderFirst(ctx, name) {
    const n = allocBytes(name);
    return readStringRef(instance.exports.pulse_request_header_first(ctx, n.ptr, n.len));
  }
  function requestHeaderCount(ctx, name) {
    const n = allocBytes(name);
    return instance.exports.pulse_request_header_count(ctx, n.ptr, n.len);
  }
  function requestHeaderAt(ctx, name, index) {
    const n = allocBytes(name);
    return readStringRef(instance.exports.pulse_request_header_at(ctx, n.ptr, n.len, index));
  }
  function responseHeaderSet(ctx, name, value) {
    const n = allocBytes(name); const v = allocBytes(value);
    instance.exports.pulse_response_header_set(ctx, n.ptr, n.len, v.ptr, v.len);
  }
  function responseHeaderAppend(ctx, name, value) {
    const n = allocBytes(name); const v = allocBytes(value);
    instance.exports.pulse_response_header_append(ctx, n.ptr, n.len, v.ptr, v.len);
  }
  function responseHeaderDelete(ctx, name) {
    const n = allocBytes(name);
    instance.exports.pulse_response_header_delete(ctx, n.ptr, n.len);
  }
  function requestHeadersClear() { instance.exports.pulse_bridge_request_headers_clear(); }
  function requestHeaderAppend(name, value) {
    const n = allocBytes(name); const v = allocBytes(value);
    instance.exports.pulse_bridge_request_header_append(n.ptr, n.len, v.ptr, v.len);
  }
  function readResultHeaders() {
    const headers = [];
    const count = instance.exports.pulse_result_header_count();
    for (let i = 0; i < count; i += 1) {
      headers.push({
        name: readBytes(instance.exports.pulse_result_header_name_ptr(i), instance.exports.pulse_result_header_name_len(i)),
        value: readBytes(instance.exports.pulse_result_header_value_ptr(i), instance.exports.pulse_result_header_value_len(i))
      });
    }
    return headers;
  }
  function headerValues(headers, name) {
    const lower = String(name).toLowerCase();
    return headers.filter((header) => String(header.name).toLowerCase() === lower).map((header) => header.value);
  }
  function makeError(code, message, status) {
    const c = allocBytes(code); const m = allocBytes(message);
    return instance.exports.pulse_error(c.ptr, c.len, m.ptr, m.len, status);
  }

  const importObject = {
    env: { abort(message, file, line, column) { throw new Error(`AssemblyScript abort(${message}, ${file}, ${line}, ${column})`); } },
    pulsewasm_handlers: {},
    pulsewasm_broadcaster: { broadcast(channelsRef, ctxRef) { broadcasterCalls.push({ channelsRef, ctxRef }); return 0; } }
  };

  for (const imp of imports) {
    if (imp.module === 'pulsewasm_handlers') {
      importObject.pulsewasm_handlers[imp.name] = (a, b, c) => {
        handlerCalls[imp.name] = (handlerCalls[imp.name] || 0) + 1;
        if (imp.name === 'auth') {
          const first = requestHeaderFirst(a, 'X-Pulse-Test');
          const multiCount = requestHeaderCount(a, 'X-Pulse-Multi');
          const multiSecond = requestHeaderAt(a, 'X-Pulse-Multi', 1);
          if (first !== undefined && observedHeaders.requestFirst === undefined) observedHeaders.requestFirst = first;
          if (multiCount > (observedHeaders.requestMultiCount || 0)) observedHeaders.requestMultiCount = multiCount;
          if (multiSecond !== undefined && observedHeaders.requestMultiSecond === undefined) observedHeaders.requestMultiSecond = multiSecond;
          stateSet(a, 'auth', '1');
          instance.exports.pulse_next(a);
          return 0;
        }
        if (imp.name === 'gateway') {
          observedState.gatewaySawAuth = stateGet(a, 'auth');
          instance.exports.pulse_next(a);
          return 0;
        }
        if (imp.name === 'computeHandler') {
          const id = getParam(a, 'id');
          observedParams.computeId = id;
          responseHeaderAppend(a, 'Temp-Header', 'remove-me');
          responseHeaderDelete(a, 'Temp-Header');
          responseHeaderSet(a, 'Content-Type', 'text/plain');
          setResultText(a, 201, `compute:${id}`);
          return 0;
        }
        if (imp.name === 'realtimeHandler') {
          const id = getParam(a, 'id');
          observedParams.realtimeId = id;
          responseHeaderSet(a, 'Content-Type', 'text/plain');
          responseHeaderSet(a, 'Grip-Hold', 'stream');
          responseHeaderAppend(a, 'Grip-Channel', 'realtime');
          responseHeaderAppend(a, 'Grip-Channel', `realtime:${id}`);
          setResultText(a, 200, `realtime:${id}`);
          return 0;
        }
        if (imp.name === 'bundleChannel') return 0xC0DE;
        if (imp.name === 'onConnect' || imp.name === 'onDisconnect') return 0;
        if (imp.name.toLowerCase().includes('error')) { instance.exports.pulse_next(a || b || c || 0); return 0; }
        return 0;
      };
    }
  }

  instance = new WebAssembly.Instance(module, importObject);

  function executeRequest(methodCode, requestPath, headers = []) {
    requestHeadersClear();
    for (const header of headers) requestHeaderAppend(header.name, header.value);
    const pathBytes = allocBytes(requestPath);
    const status = instance.exports.pulse_execute_request(methodCode, pathBytes.ptr, pathBytes.len);
    const resultHeaders = readResultHeaders();
    return {
      status,
      resultStatus: instance.exports.pulse_result_status(),
      resultKind: instance.exports.pulse_result_kind(),
      body: readBytes(instance.exports.pulse_result_body_ptr(), instance.exports.pulse_result_body_len()),
      headers: resultHeaders,
      headerCount: resultHeaders.length,
      gripChannels: headerValues(resultHeaders, 'Grip-Channel'),
      errorRef: instance.exports.pulse_result_error_ref(),
      streamRef: instance.exports.pulse_result_stream_ref ? instance.exports.pulse_result_stream_ref() : 0,
      responseRef: instance.exports.pulse_result_response_ref ? instance.exports.pulse_result_response_ref() : 0,
      lastChannelsRef: instance.exports.pulse_bridge_last_channels_ref(),
      lastBroadcastResult: instance.exports.pulse_bridge_last_broadcast_result(),
      invokedHandlers: instance.exports.pulse_bridge_last_invoked_handlers()
    };
  }

  function executeLifecycle(kind, methodCode, requestPath) {
    const pathBytes = allocBytes(requestPath);
    const fn = kind === 'connect' ? instance.exports.pulse_execute_connect : instance.exports.pulse_execute_disconnect;
    return fn(methodCode, pathBytes.ptr, pathBytes.len);
  }

  const methodGet = instance.exports.pulse_bridge_method_get();
  const methodPost = instance.exports.pulse_bridge_method_post();
  const realtime = executeRequest(methodGet, '/realtime/abc', [
    { name: 'X-Pulse-Test', value: 'edge' },
    { name: 'X-Pulse-Multi', value: 'one' },
    { name: 'x-pulse-multi', value: 'two' }
  ]);
  const compute = executeRequest(methodPost, '/compute/42', [{ name: 'X-Pulse-Test', value: 'edge' }]);
  const missing = executeRequest(methodGet, '/missing');
  const connectInvoked = executeLifecycle('connect', methodGet, '/realtime/abc');
  const disconnectInvoked = executeLifecycle('disconnect', methodGet, '/realtime/abc');
  const error = makeError('PULSEWASM_TEST', 'host bridge error', 599);
  const errorCode = readStringRef(instance.exports.pulse_error_code_ref(error));
  const errorMessage = readStringRef(instance.exports.pulse_error_message_ref(error));

  const checks = [
    { name: 'route_count', expected: 2, actual: instance.exports.pulse_bridge_route_count() },
    { name: 'execution_entry_count', expected: 8, actual: instance.exports.pulse_bridge_execution_entry_count() },
    { name: 'handler_binding_count', expected: 7, actual: instance.exports.pulse_bridge_handler_binding_count() },
    { name: 'request_realtime_status', expected: 200, actual: realtime.status },
    { name: 'request_realtime_body', expected: 'realtime:abc', actual: realtime.body },
    { name: 'request_realtime_param', expected: 'abc', actual: observedParams.realtimeId },
    { name: 'request_realtime_broadcaster', expected: 1, actual: broadcasterCalls.length >= 1 ? 1 : 0 },
    { name: 'request_header_first', expected: 'edge', actual: observedHeaders.requestFirst },
    { name: 'request_header_multi_count', expected: 2, actual: observedHeaders.requestMultiCount },
    { name: 'request_header_multi_second', expected: 'two', actual: observedHeaders.requestMultiSecond },
    { name: 'response_header_count', expected: 4, actual: realtime.headerCount },
    { name: 'response_header_grip_channel_count', expected: 2, actual: realtime.gripChannels.length },
    { name: 'response_header_grip_channel_second', expected: 'realtime:abc', actual: realtime.gripChannels[1] },
    { name: 'request_compute_status', expected: 201, actual: compute.status },
    { name: 'request_compute_body', expected: 'compute:42', actual: compute.body },
    { name: 'response_header_delete', expected: 0, actual: headerValues(compute.headers, 'Temp-Header').length },
    { name: 'request_compute_param', expected: '42', actual: observedParams.computeId },
    { name: 'ctx_state_map_bridge', expected: '1', actual: observedState.gatewaySawAuth },
    { name: 'missing_fallthrough_status', expected: 404, actual: missing.status },
    { name: 'connect_lifecycle_invoked', expected: 1, actual: connectInvoked },
    { name: 'disconnect_lifecycle_invoked', expected: 1, actual: disconnectInvoked },
    { name: 'error_code_ref', expected: 'PULSEWASM_TEST', actual: errorCode },
    { name: 'error_message_ref', expected: 'host bridge error', actual: errorMessage },
    { name: 'handler_auth_called', expected: 1, actual: handlerCalls.auth >= 1 ? 1 : 0 },
    { name: 'handler_gateway_called', expected: 1, actual: handlerCalls.gateway >= 1 ? 1 : 0 },
    { name: 'handler_realtime_called', expected: 1, actual: handlerCalls.realtimeHandler >= 1 ? 1 : 0 },
    { name: 'handler_compute_called', expected: 1, actual: handlerCalls.computeHandler >= 1 ? 1 : 0 },
    { name: 'handler_channel_called', expected: 1, actual: handlerCalls.bundleChannel >= 1 ? 1 : 0 }
  ].map((check) => ({ ...check, status: check.actual === check.expected ? 'ok' : 'error', message: check.actual === check.expected ? undefined : `Expected ${check.expected}, got ${check.actual}.` }));

  return {
    imports,
    exports,
    checks,
    handlerCalls,
    broadcasterCalls,
    observedParams,
    observedState,
    observedHeaders,
    results: { realtime, compute, missing, connectInvoked, disconnectInvoked, errorCode, errorMessage },
    memoryExported: Boolean(instance.exports.memory),
    instanceExports: Object.keys(instance.exports)
  };
}

function buildArtifact(options = {}) {
  const cwd = options.cwd || process.cwd();
  const diagnostics = options.diagnostics || [];
  const checks = options.bridge?.checks || [];
  const failedChecks = checks.filter((check) => check.status !== 'ok');
  return normalizeArtifact({
    version: WASM_BRIDGE_VERSION,
    generatedBy: options.generatedBy || PACKAGE_VERSION,
    status: diagnostics.length || failedChecks.length ? 'error' : 'ok',
    sourceWasmHostAbiVersion: options.wasmHostAbi?.artifact?.version,
    sourceAssemblyScriptCoreVersion: options.core?.artifact?.version,
    policy: {
      phase: WASM_BRIDGE_PHASE,
      sourceOfTruth: 'wasm-host-abi.json + request-result-headers.json + generated/as/*.as.ts',
      reReadsSource: false,
      reInfersRouteSemantics: false,
      compiler: 'assemblyscript asc',
      wasmCompiled: true,
      wasmInstantiated: Boolean(options.bridge),
      wasmExecutedThroughHostAbi: Boolean(options.bridge),
      hostBridgeImplemented: true,
      platformBindings: false,
      witBindings: false,
      wasiHttp: false,
      stringAbi: 'host writes UTF-8 through pulse_alloc; wasm decodes ptr + byteLen',
      handlers: 'host imports call exported continuation/result/ctx/header operations',
      headers: 'ordered repeated request/response headers implemented; result headers exported by iteration',
      bodyPolicy: 'request body deferred; RESULT_TEXT/JSON/EMPTY implemented; RESULT_STREAM implemented for host-owned pass-through; RESULT_BINARY reserved',
      broadcaster: 'host import required; missing broadcaster rejected during instantiation'
    },
    compiler: {
      package: 'assemblyscript',
      version: options.assemblyScriptVersion,
      executable: options.asc?.display
    },
    command: options.command,
    result: options.result ? { exitCode: options.result.status, signal: options.result.signal, durationMs: options.durationMs, stdout: String(options.result.stdout || ''), stderr: String(options.result.stderr || '') } : undefined,
    generated: { inputFiles: options.inputFiles || [], outputFiles: options.outputFiles || [] },
    wasmModule: options.bridge ? { imports: options.bridge.imports, exports: options.bridge.exports, memoryExported: options.bridge.memoryExported, instanceExports: options.bridge.instanceExports } : undefined,
    bridge: options.bridge ? {
      checks: options.bridge.checks,
      failedChecks,
      handlerCalls: options.bridge.handlerCalls,
      broadcasterCalls: options.bridge.broadcasterCalls.length,
      observedParams: options.bridge.observedParams,
      observedState: options.bridge.observedState,
      observedHeaders: options.bridge.observedHeaders,
      results: options.bridge.results
    } : undefined,
    missingBroadcaster: options.missingBroadcaster,
    diagnostics,
    warnings: options.warnings || [],
    summary: {
      compiled: Boolean(options.outputFiles && options.outputFiles.length),
      instantiated: Boolean(options.bridge),
      executed: Boolean(options.bridge),
      hostBridge: Boolean(options.bridge),
      checks: checks.length,
      failedChecks: failedChecks.length,
      handlerCalls: options.bridge ? Object.values(options.bridge.handlerCalls).reduce((sum, value) => sum + Number(value || 0), 0) : 0,
      broadcasterCalls: options.bridge ? options.bridge.broadcasterCalls.length : 0,
      headersAdapted: Boolean(options.bridge),
      requestHeaderChecks: checks.filter((check) => check.name.startsWith('request_header_')).length,
      responseHeaderChecks: checks.filter((check) => check.name.startsWith('response_header_')).length,
      repeatedHeadersPreserved: Boolean(options.bridge?.results?.realtime?.gripChannels?.length === 2),
      missingBroadcasterRejected: Boolean(options.missingBroadcaster?.missingBroadcasterRejected),
      wasmBytes: options.outputFiles?.find((file) => file.kind === 'wasm-host-bridge-output')?.bytes || 0,
      watBytes: options.outputFiles?.find((file) => file.kind === 'wat-host-bridge-output')?.bytes || 0,
      diagnostics: diagnostics.length,
      warnings: (options.warnings || []).length,
      platformBindings: false,
      witBindings: false
    }
  }, cwd);
}

function buildWasmHostBridge(shape, core, wasmHostAbi, options = {}) {
  const cwd = options.cwd || process.cwd();
  const generatedBy = options.generatedBy || PACKAGE_VERSION;
  const diagnostics = [];
  const bridgeRunnerText = buildBridgeRunnerSource();
  const stagingDir = fs.mkdtempSync(path.join(os.tmpdir(), 'pulsewasm-host-bridge-'));
  const inputFiles = writeStagedFiles(stagingDir, shape, core, bridgeRunnerText);
  const compile = compileBridge(stagingDir, cwd, options);
  diagnostics.push(...(compile.diagnostics || []));

  let outputFiles = [];
  let bridge;
  let missingBroadcaster;
  if (diagnostics.length === 0 && compile.wasmFile && fs.existsSync(compile.wasmFile)) {
    outputFiles = [fileRecord(compile.wasmFile, cwd, 'wasm-host-bridge-output'), fileRecord(compile.watFile, cwd, 'wat-host-bridge-output')];
    try {
      missingBroadcaster = instantiateWithoutBroadcaster(compile.wasmFile);
      bridge = instantiateAndRunBridge(compile.wasmFile);
      const failed = bridge.checks.filter((check) => check.status !== 'ok');
      if (failed.length > 0) diagnostics.push(diagnosticFromParts({ phase: 'wasm-host-bridge', code: 'PULSEWASM_WASM_HOST_BRIDGE_CHECK_FAILED', message: 'Phase 10D Wasm host bridge checks failed.', hint: 'Inspect wasm-host-bridge.json bridge.failedChecks for details.', details: { failed } }));
      if (!missingBroadcaster.missingBroadcasterRejected) diagnostics.push(diagnosticFromParts({ phase: 'wasm-host-bridge', code: 'PULSEWASM_WASM_HOST_BRIDGE_BROADCASTER_NOT_REQUIRED', message: 'The Phase 10D bridge did not reject a missing broadcaster import.', hint: 'Channel-resolving builds must require the broadcaster import at this boundary.', details: missingBroadcaster }));
    } catch (error) {
      diagnostics.push(diagnosticFromParts({ phase: 'wasm-host-bridge', code: 'PULSEWASM_WASM_HOST_BRIDGE_EXECUTION_FAILED', message: 'Phase 10D Wasm host bridge execution failed.', hint: 'Inspect details for the host-side execution error.', details: { message: error && error.message ? error.message : String(error), stack: error && error.stack ? error.stack : undefined } }));
    }
  }

  const command = compile.asc ? {
    executable: compile.asc.display,
    args: [path.relative(cwd, path.join(stagingDir, BRIDGE_RUNNER_FILE)).replace(/\\/g, '/'), '--outFile', path.join(options.outDir ? path.relative(cwd, path.resolve(cwd, options.outDir)) : 'artifacts', BRIDGE_WASM_REL).replace(/\\/g, '/'), '--textFile', path.join(options.outDir ? path.relative(cwd, path.resolve(cwd, options.outDir)) : 'artifacts', BRIDGE_WAT_REL).replace(/\\/g, '/'), '--runtime', 'stub', '--noAssert']
  } : undefined;

  const artifact = buildArtifact({ cwd, generatedBy, shape, core, wasmHostAbi, diagnostics, warnings: compile.warnings || [], asc: compile.asc, command, result: compile.result, durationMs: compile.durationMs, inputFiles, outputFiles, bridge, missingBroadcaster, assemblyScriptVersion: assemblyScriptVersion(cwd) });
  return { artifact, files: [{ file: BRIDGE_RUNNER_FILE, text: bridgeRunnerText }], outputFiles, diagnostics };
}

