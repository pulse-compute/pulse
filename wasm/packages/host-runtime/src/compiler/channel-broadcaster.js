'use strict';

const { PACKAGE_VERSION, normalizeArtifact } = require('@pulse-compute/wasm-contracts/diagnostics');
const {
  CHANNEL_BROADCASTER_VERSION,
  CHANNEL_BROADCASTER_PHASE,
  BROADCASTER_MISSING_CODE,
  channelAbiContract,
  broadcasterImportContract
} = loadContractsChannelBroadcaster();

function loadContractsChannelBroadcaster() {
  try {
    return require('@pulse-compute/wasm-contracts/host/channel-broadcaster');
  } catch (error) {
    if (error && error.code === 'MODULE_NOT_FOUND' && String(error.message).includes('@pulse-compute/wasm-contracts')) {
      return require('../../../contracts/src/host/channel-broadcaster.js');
    }
    throw error;
  }
}

function channelKind(channel) {
  if (!channel) return 'none';
  if (channel.kind === 'handler') return 'handler';
  if (channel.kind === 'static') return 'static';
  return channel.kind || 'unknown';
}

function collectChannelUses(dispatchTable, executionPlan) {
  const routeUses = [];
  for (const route of dispatchTable?.routes || []) {
    const channel = route.execution?.channel || route.channel;
    if (!channel) continue;
    routeUses.push({
      kind: 'route',
      runtimeId: route.runtimeId,
      stableId: route.stableId,
      method: route.method,
      path: route.path,
      channelKind: channelKind(channel),
      slot: Number.isInteger(channel.slot) ? channel.slot : undefined,
      handlerId: channel.id || channel.handlerId,
      name: channel.name,
      staticValue: channel.kind === 'static' ? channel.value : undefined
    });
  }

  const scopeUses = [];
  for (const scope of executionPlan?.scopes || []) {
    if (!scope.channel) continue;
    const channel = scope.channel;
    scopeUses.push({
      kind: 'scope',
      scopeId: scope.id,
      channelKind: channelKind(channel),
      slot: Number.isInteger(channel.slot) ? channel.slot : undefined,
      handlerId: channel.id || channel.handlerId,
      name: channel.name,
      staticValue: channel.kind === 'static' ? channel.value : undefined
    });
  }

  return { routeUses, scopeUses };
}

function buildMarkdown(artifact) {
  const lines = [];
  lines.push('# PulseWasm Channel / Broadcaster Adaptor Contract v1');
  lines.push('');
  lines.push(`Generated by: \`${artifact.generatedBy}\``);
  lines.push(`Phase: \`${artifact.policy.phase}\``);
  lines.push('');
  lines.push('## Locked positions');
  lines.push('');
  for (const item of artifact.lockedPositions) lines.push(`- ${item}`);
  lines.push('');
  lines.push('## Channel representation');
  lines.push('');
  lines.push(`- Channel handler signature: \`${artifact.channelAbi.handlerSignature}\``);
  lines.push(`- ChannelsRef: \`${artifact.channelAbi.channelsRef}\``);
  lines.push(`- Ordered: \`${artifact.channelAbi.ordered}\``);
  lines.push(`- Empty channel list behavior: \`${artifact.channelAbi.emptyListBehavior}\``);
  lines.push('');
  lines.push('## Host-visible channel exports');
  lines.push('');
  for (const item of artifact.channelAbi.exports) lines.push(`- \`${item}\``);
  lines.push('');
  lines.push('## Broadcaster import');
  lines.push('');
  lines.push(`- Module: \`${artifact.broadcaster.module}\``);
  lines.push(`- Name: \`${artifact.broadcaster.name}\``);
  lines.push(`- Signature: \`${artifact.broadcaster.signature}\``);
  lines.push(`- Return policy: \`${artifact.broadcaster.returnPolicy}\``);
  lines.push(`- Required when channels resolve: \`${artifact.broadcaster.requiredWhenChannelsResolve}\``);
  lines.push('');
  lines.push('## Failure');
  lines.push('');
  lines.push(`- Code: \`${artifact.broadcaster.missingFailure.code}\``);
  lines.push(`- Status: \`${artifact.broadcaster.missingFailure.statusCode}\``);
  lines.push(`- Message: \`${artifact.broadcaster.missingFailure.message}\``);
  lines.push('');
  lines.push('## GRIP / headers');
  lines.push('');
  lines.push('Channel resolution does not invent a separate GRIP side channel. GRIP/Fanout framing remains expressed through normal ordered response headers such as `Grip-Hold` and repeated `Grip-Channel`.');
  lines.push('');
  lines.push('## Summary');
  lines.push('');
  for (const [key, value] of Object.entries(artifact.summary)) lines.push(`- ${key}: \`${value}\``);
  lines.push('');
  return `${lines.join('\n')}\n`;
}

function buildChannelBroadcaster(dispatchTable, executionPlan, options = {}) {
  const cwd = options.cwd || process.cwd();
  const generatedBy = options.generatedBy || PACKAGE_VERSION;
  const channelHandlers = Number(dispatchTable?.summary?.channelHandlers || 0);
  const staticChannels = Number(dispatchTable?.summary?.staticChannels || 0);
  const { routeUses, scopeUses } = collectChannelUses(dispatchTable, executionPlan);
  const channelsMayResolve = routeUses.length > 0 || scopeUses.length > 0 || channelHandlers > 0 || staticChannels > 0;

  const artifact = normalizeArtifact({
    version: CHANNEL_BROADCASTER_VERSION,
    generatedBy,
    source: dispatchTable?.source,
    policy: {
      phase: CHANNEL_BROADCASTER_PHASE,
      status: 'locked-contract-and-local-bridge-proof',
      sourceOfTruth: [
        'dispatch-table.json',
        'execution-plan.json',
        'wasm-host-abi.json',
        'request-result-headers.json',
        'pulsewasm channel/broadcaster adaptor contract v1'
      ],
      contractOnly: true,
      platformBindings: false,
      gripImplementation: false,
      broadcasterAdaptorRequired: channelsMayResolve,
      silentIgnoreForbidden: true
    },
    lockedPositions: [
      'Channel resolution is a real routing artifact.',
      'Channel handlers return ChannelsRef through the locked ChannelHandler ABI.',
      'ChannelsRef is an ordered list of one or more StringRef channel names.',
      'Static channels and handler-produced channels are normalized to the same ChannelsRef surface.',
      'If no channel resolves, no broadcaster call occurs.',
      'If one or more channels resolve and a broadcaster adaptor exists, broadcaster.broadcast(channelsRef, ctxRef) is invoked.',
      'If one or more channels resolve and the broadcaster adaptor is missing, the runtime/host bridge fails explicitly.',
      'Broadcaster failure returns an ErrorRef through the broadcaster return value.',
      'GRIP/Fanout framing remains represented through normal ordered response headers, not a hidden side channel.'
    ],
    channelAbi: channelAbiContract(),
    broadcaster: broadcasterImportContract({ requiredWhenChannelsResolve: channelsMayResolve }),
    grip: {
      implementedHere: false,
      framedThroughHeaders: true,
      headers: ['Grip-Hold', 'Grip-Channel'],
      repeatedGripChannelPreserved: true,
      adaptorFuture: 'GRIP/Fanout adaptor may translate ChannelsRef into ordered response headers and/or platform broadcaster calls.'
    },
    channelUses: {
      routes: routeUses,
      scopes: scopeUses
    },
    summary: {
      routes: Array.isArray(dispatchTable?.routes) ? dispatchTable.routes.length : 0,
      executionEntries: Array.isArray(executionPlan?.entries) ? executionPlan.entries.length : 0,
      scopes: Array.isArray(executionPlan?.scopes) ? executionPlan.scopes.length : 0,
      routeChannelUses: routeUses.length,
      scopeChannelUses: scopeUses.length,
      channelHandlers,
      staticChannels,
      channelsMayResolve,
      broadcasterRequiredWhenChannelsResolve: channelsMayResolve,
      missingBroadcasterFailureCode: BROADCASTER_MISSING_CODE,
      gripHeadersModeledThroughHeaders: true,
      platformBindings: false
    }
  }, cwd);

  return {
    artifact,
    files: [
      { file: 'generated/host/channel-broadcaster.md', text: buildMarkdown(artifact) }
    ],
    diagnostics: []
  };
}

module.exports = {
  CHANNEL_BROADCASTER_VERSION,
  buildChannelBroadcaster
};
