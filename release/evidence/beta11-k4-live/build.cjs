'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=__dirname, packedRoot=path.join(root,'consumer');
const {toolchain,project}=require('../pulse-beta11-review/wasm/test/kv/k4/toolchain.cjs');
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
project(packedRoot,packedRoot);
const authFile=path.join(root,'probe-auth');
if(!fs.existsSync(authFile))fs.writeFileSync(authFile,crypto.randomBytes(32).toString('hex'),{mode:0o600});
const auth=fs.readFileSync(authFile,'utf8').trim();
const src=path.join(packedRoot,'src/index.ts');
const source=fs.readFileSync(src,'utf8').replace('export default async function handler(ctx: PulseContext) {',`export default async function handler(ctx: PulseContext) {\n  if (ctx.req.header('x-pulse-k4-auth') !== '${auth}') return ctx.text('unauthorized', { status: 401 });`);
fs.writeFileSync(src,source);
const tools=toolchain(packedRoot);
const built=tools.buildProject(tools.resolveProject({cwd:packedRoot,profile:'fastly-native'}));
if(built.status!=='built')throw Error('K4 build failed');
const wasm=fs.readFileSync(path.join(built.outDir,'bin/main.wasm'));
const products=Object.keys(require.cache).filter(p=>/pulse-beta11(?:-review)?\/(packages|wasm\/packages)\//.test(p));
if(products.length)throw Error('Workspace product module loaded');
const receipt={source:'67c984d8dc223dd94d1146353534b12a89e0e50b',installedArtifactSha256:'2de79c3f72776cda7ca2d575c7e69dfbc55e8e418523d1c11ae74911d1496324',buildStatus:built.status,outDir:built.outDir,moduleSha256:sha(wasm),moduleBytes:wasm.length,consumerSourceSha256:sha(source),fixtureChange:'K2 command handler unchanged after one private test-authentication header guard',workspaceProductModules:products.length};
fs.writeFileSync(path.join(root,'build.json'),JSON.stringify(receipt,null,2)+'\n');
