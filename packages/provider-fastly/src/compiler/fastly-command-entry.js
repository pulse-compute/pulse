function sha256Text(text) { return crypto.createHash('sha256').update(String(text || ''), 'utf8').digest('hex'); }
function sha256Buffer(buffer) { return crypto.createHash('sha256').update(buffer).digest('hex'); }
function makeFile(file, text) { return { file, text, bytes: Buffer.byteLength(text, 'utf8'), sha256: sha256Text(text) }; }
function normalizeSlash(value) { return String(value || '').replace(/\\/g, '/'); }
function truncate(value, max = 12000) { const text = String(value || ''); return text.length > max ? `${text.slice(0, max)}\n…<truncated ${text.length - max} chars>` : text; }
function diag(code, message, hint, details) {
  return normalizeDiagnostic({ phase: 'fastly-command-entry', severity: 'error', code, message, hint, details, loc: { file: '<fastly-command-entry>' } });
}
function fileRecord(filePath, cwd, kind) {
  const buffer = fs.readFileSync(filePath);
  return { file: normalizeSlash(path.relative(cwd, filePath)), kind, bytes: buffer.length, sha256: sha256Buffer(buffer) };
}

function buildFastlyCommandEntrySource() {
  return `/* Generated by PulseWasm.
 * Fastly command-style entrypoint proof.
 * This module is Fastly-target-specific. It deliberately exports _start.
 * It is not the generic PulseWasm runtime and it is not an SDK dependency.
 */
type FastlyStatus = i32;
type BodyHandle = u32;
type BodyWriteEnd = u32;
type ResponseHandle = u32;
type ptr = usize;
type strptr = ArrayBuffer;

@external("fastly_http_body", "new")
declare function fastly_http_body_new(handle_out: ptr): FastlyStatus;

@external("fastly_http_body", "write")
declare function fastly_http_body_write(
  body_handle: BodyHandle,
  buf: strptr,
  buf_len: usize,
  end: BodyWriteEnd,
  nwritten_out: ptr
): FastlyStatus;

@external("fastly_http_resp", "new")
declare function fastly_http_resp_new(resp_handle_out: ptr): FastlyStatus;

@external("fastly_http_resp", "status_set")
declare function fastly_http_resp_status_set(resp_handle: ResponseHandle, status: u16): FastlyStatus;

@external("fastly_http_resp", "header_insert")
declare function fastly_http_resp_header_insert(
  resp_handle: ResponseHandle,
  name: strptr,
  name_len: usize,
  value: strptr,
  value_len: usize
): FastlyStatus;

@external("fastly_http_resp", "send_downstream")
declare function fastly_http_resp_send_downstream(
  resp_handle: ResponseHandle,
  body_handle: BodyHandle,
  streaming: u32
): FastlyStatus;

function check(status: FastlyStatus): void {
  if (status != 0) unreachable();
}

function outPtr(): usize {
  const ptr = __alloc(4);
  store<u32>(ptr, 0);
  return ptr;
}

function writeHeader(resp: ResponseHandle, name: string, value: string): void {
  const encodedName = String.UTF8.encode(name, false);
  const encodedValue = String.UTF8.encode(value, false);
  check(fastly_http_resp_header_insert(resp, encodedName, encodedName.byteLength, encodedValue, encodedValue.byteLength));
}

function writeBody(body: BodyHandle, text: string): void {
  const bytes = String.UTF8.encode(text, false);
  const writtenOut = outPtr();
  check(fastly_http_body_write(body, bytes, bytes.byteLength, 0, writtenOut));
}

export function __pulsewasm_abort(message: string | null, fileName: string | null, line: u32, column: u32): void {
  unreachable();
}

export function _start(): void {
  const responseOut = outPtr();
  check(fastly_http_resp_new(responseOut));
  const response = load<ResponseHandle>(responseOut);

  const bodyOut = outPtr();
  check(fastly_http_body_new(bodyOut));
  const body = load<BodyHandle>(bodyOut);

  check(fastly_http_resp_status_set(response, 200));
  writeHeader(response, "Content-Type", "text/plain; charset=utf-8");
  writeHeader(response, "X-PulseWasm-Fastly", "13C.1");
  writeBody(body, "pulsewasm fastly command entrypoint ok\\n");
  check(fastly_http_resp_send_downstream(response, body, 0));
}
`;
}

