function buildPackagingSmoke({ cwd, outDir, wasmSource, generatedBy }) {
  const fastlyVersion = spawnSync('fastly', ['--version'], { cwd, encoding: 'utf8', timeout: 10_000 });
  const fastlyAvailable = !fastlyVersion.error && fastlyVersion.status === 0;
  const targetDir = path.join(outDir, 'generated', 'fastly');
  fs.mkdirSync(targetDir, { recursive: true });
  const wasmTarget = path.join(targetDir, 'pulsewasm-compute.wasm');
  let copied = false;
  let copiedRecord;
  if (wasmSource && fs.existsSync(wasmSource)) {
    fs.copyFileSync(wasmSource, wasmTarget);
    copied = true;
    copiedRecord = fileRecord(wasmTarget, cwd, 'fastly-compute-wasm-candidate');
  }
  const packCommand = 'fastly compute pack --wasm-binary artifacts/generated/fastly/pulsewasm-compute.wasm';
  return {
    version: FASTLY_PACKAGING_SMOKE_VERSION,
    generatedBy,
    phase: PHASE,
    status: 'ok',
    fastlyCli: {
      available: fastlyAvailable,
      versionOutput: fastlyAvailable ? String(fastlyVersion.stdout || fastlyVersion.stderr || '').trim() : undefined,
      error: fastlyAvailable ? undefined : (fastlyVersion.error ? fastlyVersion.error.message : `exit ${fastlyVersion.status}`)
    },
    commands: {
      pack: packCommand,
      serve: 'fastly compute serve',
      deploy: 'fastly compute deploy'
    },
    packageCandidate: {
      wasmCopied: copied,
      wasm: copiedRecord,
      fastlyToml: 'generated/fastly/fastly.toml',
      readme: 'generated/fastly/README.md'
    },
    execution: {
      packExecuted: false,
      serveExecuted: false,
      deployExecuted: false,
      reason: fastlyAvailable
        ? 'Fastly CLI is available, but this artifact does not execute pack/serve automatically; use the external reality task.'
        : 'The Fastly CLI local Compute lifecycle was not available in this environment, so the generator emitted a pack-ready scaffold and ran the mock adapter smoke only.'
    },
    summary: {
      fastlyCliAvailable: fastlyAvailable,
      wasmCopied: copied,
      packageGenerated: false,
      packExecuted: false,
      serveExecuted: false,
      deployExecuted: false
    }
  };
}

function loadModuleFromText(text, filePath) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, text, 'utf8');
  delete require.cache[filePath];
  return require(filePath);
}

function runFastlyLocalSmoke({ compiledWasmRuntime, adapterSource, wasmFile, cwd }) {
  const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'pulsewasm-fastly-adapter-'));
  const hostFile = findFile(compiledWasmRuntime?.files, 'generated/host/compiled-wasm-host-runtime.cjs');
  if (!hostFile) throw new Error('compiled-wasm-host-runtime.cjs was not available from the compiled-wasm runtime output.');
  const hostModule = loadModuleFromText(hostFile.text, path.join(tempDir, 'compiled-wasm-host-runtime.cjs'));
  const adapterModule = loadModuleFromText(adapterSource, path.join(tempDir, 'fastly-adapter.cjs'));

  const runtime = hostModule.createPulseWasmCompiledHostRuntime({
    wasmPath: wasmFile,
    deploymentPosture: { engine: 'wasm', wasmOptimized: true },
    hostResponses: {
      77: {
        status: 206,
        headers: [
          ['Content-Type', 'application/octet-stream'],
          ['Cache-Control', 'public, max-age=60'],
          ['Grip-Channel', 'backend:stream'],
          ['Server', 'origin']
        ],
        bodyStream: { kind: 'mock-fastly-body', chunks: ['asset:', '42'] }
      }
    }
  });

  const adapter = adapterModule.createFastlyStreamHeaderAdapter({ runtime });
  const streamResponse = adapter.handleRequest({
    method: 'GET',
    path: '/stream',
    rawHeaders: ['X-Trace', 'abc', 'Grip-Channel', 'client:a', 'Grip-Channel', 'client:b']
  });
  const schemaResponse = adapter.handleRequest({
    method: 'POST',
    path: '/users',
    rawHeaders: ['Content-Type', 'application/json'],
    bodyText: '{"name":"Ada","age":42,"active":true}'
  });
  const missingResponse = adapter.handleRequest({ method: 'GET', path: '/missing' });

  function values(headers, name) {
    return (headers || []).filter(([key]) => String(key).toLowerCase() === String(name).toLowerCase()).map(([, value]) => value);
  }
  const firstRequest = adapter.observed.requests[0];
  const checks = [];
  function check(name, expected, actual) {
    checks.push({ name, expected, actual, status: Object.is(expected, actual) ? 'ok' : 'error', message: Object.is(expected, actual) ? undefined : `Expected ${expected}, got ${actual}.` });
  }
  check('fastly_request_path_mapped', '/stream', firstRequest.path);
  check('fastly_request_method_mapped', 'GET', firstRequest.method);
  check('fastly_repeated_request_headers_preserved', 2, values(firstRequest.headers, 'Grip-Channel').length);
  check('stream_status', 206, streamResponse.status);
  check('stream_kind', 'stream', streamResponse.kind);
  check('stream_body_forwarded', 'asset:42', streamResponse.body);
  check('stream_response_ref_visible', 77, streamResponse.responseRef);
  check('backend_content_type_preserved', 'application/octet-stream', values(streamResponse.headers, 'Content-Type')[0]);
  check('cache_control_overridden', 'public, max-age=120', values(streamResponse.headers, 'Cache-Control')[0]);
  check('backend_server_header_preserved_without_delete', 1, values(streamResponse.headers, 'Server').length);
  check('grip_channel_repeated_preserved', 2, values(streamResponse.headers, 'Grip-Channel').length);
  check('schema_status', 201, schemaResponse.status);
  check('schema_kind', 'json', schemaResponse.kind);
  check('schema_body', '{"name":"Ada","age":42,"active":true}', schemaResponse.body);
  check('missing_status', 404, missingResponse.status);
  check('no_js_handler_imports', 0, runtime.imports.filter((item) => item.module === 'pulsewasm_handlers').length);
  return {
    version: FASTLY_LOCAL_SMOKE_VERSION,
    generatedBy: PACKAGE_VERSION,
    phase: PHASE,
    status: checks.every((item) => item.status === 'ok') ? 'ok' : 'error',
    checks,
    failedChecks: checks.filter((item) => item.status !== 'ok'),
    observed: {
      requests: adapter.observed.requests,
      streamResponse,
      schemaResponse,
      missingResponse
    },
    summary: {
      executed: true,
      checks: checks.length,
      failedChecks: checks.filter((item) => item.status !== 'ok').length,
      streamHeaderProof: true,
      compiledWasmRuntimeDriven: true,
      nodeAdapterUsed: false,
      fastlyCliRequired: false,
      realFastlyHostcalls: false,
      mockHostcallSurface: true
    }
  };
}

