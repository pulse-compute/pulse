function sha256Text(text) { return crypto.createHash('sha256').update(String(text || ''), 'utf8').digest('hex'); }
function sha256Buffer(buffer) { return crypto.createHash('sha256').update(buffer).digest('hex'); }
function makeFile(file, text) { return { file, text, bytes: Buffer.byteLength(text, 'utf8'), sha256: sha256Text(text) }; }
function normalizeSlash(value) { return String(value || '').replace(/\\/g, '/'); }
function diag(code, message, hint, details) {
  return normalizeDiagnostic({ phase: 'fastly-adapter', severity: 'error', code, message, hint, details, loc: { file: '<fastly-adapter>' } });
}
function warn(code, message, hint, details) {
  return normalizeDiagnostic({ phase: 'fastly-adapter', severity: 'warning', code, message, hint, details, loc: { file: '<fastly-adapter>' } });
}
function fileRecord(filePath, cwd, kind) {
  const buffer = fs.readFileSync(filePath);
  return { file: normalizeSlash(path.relative(cwd, filePath)), kind, bytes: buffer.length, sha256: sha256Buffer(buffer) };
}
function findFile(files, fileName) {
  return (files || []).find((file) => file.file === fileName || file.file.endsWith(`/${fileName}`));
}
function findOutputFile(outputFiles, suffix) {
  return (outputFiles || []).find((file) => file.file && file.file.endsWith(suffix));
}

function buildFastlyAdapterSource() {
  return `/* Generated by PulseWasm.
 * Fastly stream/header adapter proof.
 * This is a platform-shape adapter over the compiled-Wasm host runtime.
 * It is not an official Fastly SDK and does not redefine PulseWasm semantics.
 */
'use strict';

function normalizeRawHeaders(rawHeaders) {
  if (!rawHeaders) return [];
  const headers = [];
  if (Array.isArray(rawHeaders)) {
    if (rawHeaders.length > 0 && Array.isArray(rawHeaders[0])) {
      for (const pair of rawHeaders) if (pair && pair.length >= 2) headers.push([String(pair[0]), String(pair[1])]);
      return headers;
    }
    for (let i = 0; i < rawHeaders.length; i += 2) {
      if (rawHeaders[i] !== undefined && rawHeaders[i + 1] !== undefined) headers.push([String(rawHeaders[i]), String(rawHeaders[i + 1])]);
    }
  }
  return headers;
}

function normalizeHeaders(headers) {
  if (!headers) return [];
  if (Array.isArray(headers)) return normalizeRawHeaders(headers);
  if (headers && typeof headers[Symbol.iterator] === 'function') return Array.from(headers, ([key, value]) => [String(key), String(value)]);
  return Object.entries(headers).flatMap(([key, value]) => Array.isArray(value) ? value.map((item) => [String(key), String(item)]) : [[String(key), String(value)]]);
}

function normalizeFastlyPath(request) {
  if (!request) return '/';
  if (request.path) return String(request.path || '/');
  if (request.url) {
    try { return new URL(String(request.url), 'http://fastly.local').pathname || '/'; } catch (_) { return String(request.url || '/'); }
  }
  return '/';
}

function fastlyRequestToHostRequest(request) {
  return {
    method: String((request && request.method) || 'GET').toUpperCase(),
    path: normalizeFastlyPath(request),
    headers: normalizeRawHeaders(request && request.rawHeaders).concat(normalizeHeaders(request && request.headers)),
    bodyText: request && request.bodyText !== undefined ? String(request.bodyText) : undefined
  };
}

function groupHeaderValues(headers, name) {
  const lower = String(name).toLowerCase();
  return (headers || []).filter(([key]) => String(key).toLowerCase() === lower).map(([, value]) => String(value));
}

function fastlyBodyFromHostResult(result) {
  if (!result) return '';
  if (result.kind === 'stream') {
    if (result.bodyStream && Array.isArray(result.bodyStream.chunks)) return result.bodyStream.chunks.join('');
    if (result.response && result.response.bodyStream && Array.isArray(result.response.bodyStream.chunks)) return result.response.bodyStream.chunks.join('');
    if (result.stream && Array.isArray(result.stream.chunks)) return result.stream.chunks.join('');
    return '';
  }
  if (result.body === undefined || result.body === null) return '';
  return Buffer.isBuffer(result.body) ? result.body.toString('utf8') : String(result.body);
}

function hostResultToFastlyResponse(result) {
  const headers = (result && Array.isArray(result.headers)) ? result.headers.map(([key, value]) => [String(key), String(value)]) : [];
  return {
    status: Number(result && result.status) || 500,
    kind: result && result.kind || 'unknown',
    headers,
    body: fastlyBodyFromHostResult(result),
    responseRef: result && result.responseRef || 0,
    streamRef: result && result.streamRef || 0,
    bodyStream: result && (result.bodyStream || (result.response && result.response.bodyStream) || result.stream),
    diagnostics: result && result.diagnostics || []
  };
}

function createFastlyStreamHeaderAdapter(options) {
  const runtime = options && options.runtime;
  if (!runtime || typeof runtime.executeRequest !== 'function') {
    const error = new Error('Fastly adapter requires a PulseWasm compiled host runtime.');
    error.code = 'PULSEWASM_FASTLY_RUNTIME_REQUIRED';
    throw error;
  }
  const observed = { requests: [], responses: [] };
  return {
    observed,
    executeRequest(request) {
      const hostRequest = fastlyRequestToHostRequest(request);
      observed.requests.push(hostRequest);
      const hostResult = runtime.executeRequest(hostRequest);
      const fastlyResponse = hostResultToFastlyResponse(hostResult);
      observed.responses.push(fastlyResponse);
      return fastlyResponse;
    },
    handleRequest(request) { return this.executeRequest(request); },
    executeConnect(input) { return runtime.executeConnect ? runtime.executeConnect(input || {}) : { status: 204, headers: [], kind: 'empty' }; },
    executeDisconnect(input) { return runtime.executeDisconnect ? runtime.executeDisconnect(input || {}) : { status: 204, headers: [], kind: 'empty' }; }
  };
}

module.exports = {
  createFastlyStreamHeaderAdapter,
  fastlyRequestToHostRequest,
  hostResultToFastlyResponse,
  normalizeRawHeaders,
  normalizeHeaders,
  normalizeFastlyPath,
  groupHeaderValues
};
`;
}

