'use strict';
const assert = require('node:assert/strict');
// Reused by the optional browser smoke. Tests visible behavior against input data.
module.exports = async function navigationCases(page, model) {
  const mount = model.registrations.find(r => r.kind === 'mount' && !r.mountPath.length && model.children.get(r.id)?.length);
  if (!mount) return;
  const find = id => page.locator(`.node[data-registration="${id}"]`);
  await find(mount.id).click();
  await page.locator('#focus-branch').click();
  assert.equal(await page.locator('#breadcrumbs [aria-current]').textContent(), model.label(mount));
  const contained = model.registrations.filter(r => r.id === mount.id || r.mountPath.includes(mount.id));
  assert.equal(await page.locator('#rows tr').count(), contained.length, 'table follows exact mount scope');
  assert.ok((await page.locator('#scope-status').textContent()).includes(contained.length + ' registrations in scope'));
  const child = model.children.get(mount.id)[0];
  await find(mount.id).focus(); await page.keyboard.press('ArrowRight');
  await page.waitForFunction(id => document.activeElement?.dataset.registration === id, child.id);
  assert.equal(await page.locator('.node.selected').getAttribute('data-registration'), child.id);
  await page.getByRole('button', { name: 'Previous selection', exact: true }).click();
  assert.equal(await page.locator('.node.selected').getAttribute('data-registration'), mount.id);
  await page.getByRole('button', { name: 'Next selection', exact: true }).click();
  assert.equal(await page.locator('.node.selected').getAttribute('data-registration'), child.id);
  await page.locator('#breadcrumbs').getByRole('button', { name: 'Application', exact: true }).click();
  assert.equal(await page.locator('#rows tr').count(), model.registrations.length);
  await page.locator('#expand-level').click();
  await page.locator('#fit-graph').click();
  assert.equal(await page.evaluate(() => { const v = document.getElementById('viewport').getBoundingClientRect(); return [...document.querySelectorAll('#graph .node')].every(n => { const b = n.getBoundingClientRect(); return b.left >= v.left - 2 && b.right <= v.right + 2 && b.top >= v.top - 2 && b.bottom <= v.bottom + 2; }); }), true, 'Fit contains every visible node');
  await page.locator('#zoom-reset').click();
  await page.locator('#viewport').scrollIntoViewIfNeeded();
  await page.locator('#viewport').evaluate(v => { v.scrollTop = 200; v.scrollLeft = 0; });
  const box = await page.locator('#viewport').boundingBox(), before = await page.locator('#viewport').evaluate(v => v.scrollTop);
  await page.mouse.move(box.x + 90, box.y + 200); await page.mouse.down(); await page.mouse.move(box.x + 90, box.y + 90, { steps: 5 }); await page.mouse.up();
  assert.ok(await page.locator('#viewport').evaluate(v => v.scrollTop) > before + 60, 'dragging empty canvas pans it');
  // Make both axes scrollable so pointer anchoring is tested away from scroll bounds.
  for (let i = 0; i < 4; i++) await page.getByRole('button', { name: 'Zoom in', exact: true }).click();
  const zoomBefore = parseFloat(await page.locator('#zoom-reset').textContent());
  const worldBefore = await page.locator('#viewport').evaluate(v => { const z = parseFloat(getComputedStyle(document.getElementById('graph')).zoom); return [(v.scrollLeft + 190) / z, (v.scrollTop + 180) / z]; });
  await page.mouse.move(box.x + 190, box.y + 180); await page.keyboard.down('Control'); await page.mouse.wheel(0, -100); await page.keyboard.up('Control');
  await page.waitForFunction(before => parseFloat(document.getElementById('zoom-reset').textContent) > before, zoomBefore);
  const worldAfter = await page.locator('#viewport').evaluate(v => { const z = parseFloat(getComputedStyle(document.getElementById('graph')).zoom); return [(v.scrollLeft + 190) / z, (v.scrollTop + 180) / z]; });
  assert.ok(worldBefore.every((value, i) => Math.abs(value - worldAfter[i]) < 2), 'wheel zoom preserves the graph point under the pointer');
  await page.locator('#zoom-reset').click();
  const map = await page.locator('#minimap').boundingBox();
  await page.mouse.click(map.x + map.width / 2, map.y + map.height * .8);
  assert.ok(await page.locator('#viewport').evaluate(v => v.scrollTop) > 300, 'minimap moves within the current graph');
  await page.locator('#center-selection').click();
  await page.waitForFunction(() => { const n = document.querySelector('#graph .node.selected')?.getBoundingClientRect(), v = document.getElementById('viewport').getBoundingClientRect(); return n && n.left >= v.left - 1 && n.right <= v.right + 1 && n.top >= v.top - 1 && n.bottom <= v.bottom + 1; });
  await page.locator('#minimap').focus(); await page.keyboard.press('Home');
  assert.ok(parseFloat(await page.locator('#zoom-reset').textContent()) < 100, 'keyboard minimap Home fits the graph');
  await page.locator('#zoom-reset').click();
  await page.locator('#breadcrumbs').getByRole('button', { name: 'Application', exact: true }).click();
};
